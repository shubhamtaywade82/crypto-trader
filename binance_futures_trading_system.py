class Side(Enum):
    BUY = "BUY"
    SELL = "SELL"

class PositionSide(Enum):
    LONG = "LONG"
    SHORT = "SHORT"

class Signal(Enum):
    LONG = 1
    SHORT = -1
    NEUTRAL = 0

@dataclass
class OHLCV:
    open_time: int
    open: float
    high: float
    low: float
    close: float
    volume: float
    close_time: int
    quote_volume: float
    trades: int
    taker_buy_base: float
    taker_buy_quote: float

@dataclass
class Position:
    symbol: str
    side: PositionSide          # LONG or SHORT
    entry_price: float
    quantity: float             # contract quantity (notional / entry_price)
    notional: float             # position value in USDT at entry
    margin_used: float          # notional / leverage
    leverage: int
    open_time: int
    pnl_target: float           # absolute USDT target
    catastrophic_sl: float      # absolute USDT catastrophic stop
    unrealized_pnl: float = 0.0
    realized_pnl: float = 0.0
    status: Literal["OPEN", "CLOSED"] = "OPEN"
    close_time: Optional[int] = None
    close_price: Optional[float] = None
    close_reason: Optional[str] = None

    def update_pnl(self, mark_price: float):
        """Update unrealized PnL based on current mark price."""
        if self.status != "OPEN":
            return
        if self.side == PositionSide.LONG:
            self.unrealized_pnl = (mark_price - self.entry_price) * self.quantity
        else:
            self.unrealized_pnl = (self.entry_price - mark_price) * self.quantity

    @property
    def pnl_pct(self) -> float:
        """Return PnL as percentage of margin used."""
        if self.margin_used == 0:
            return 0.0
        return self.unrealized_pnl / self.margin_used

    def to_dict(self) -> dict:
        d = asdict(self)
        d["side"] = self.side.value
        d["status"] = self.status
        return d

    @classmethod
    def from_dict(cls, data: dict) -> "Position":
        data["side"] = PositionSide(data["side"])
        return cls(**{k: v for k, v in data.items() if k in cls.__dataclass_fields__})


