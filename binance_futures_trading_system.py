class FuturesWallet:
    """
    Simulates a Binance USD-M Futures wallet.
    Tracks: wallet balance, margin balance, available balance,
            positions, realized / unrealized PnL, maintenance margin.
    """

    def __init__(
        self,
        initial_balance: float = 10_000.0,
        leverage: int = LEVERAGE,
        equity_utilization: float = EQUITY_UTILIZATION,
        pnl_target_pct: float = PNL_TARGET_PCT,
        catastrophic_sl_pct: float = CATASTROPHIC_SL_PCT,
        state_file: str = "wallet_state.json",
    ):
        self.leverage = leverage
        self.equity_utilization = equity_utilization
        self.pnl_target_pct = pnl_target_pct
        self.catastrophic_sl_pct = catastrophic_sl_pct
        self.state_file = Path(state_file)

        # Balances
        self.wallet_balance: float = initial_balance
        self.unrealized_pnl_total: float = 0.0
        self.realized_pnl_total: float = 0.0

        # Positions: symbol -> Position
        self.positions: Dict[str, Position] = {}
        self.position_history: List[dict] = []

        # Load persisted state if exists
        self._load_state()

    # -- Balance Properties --

    @property
    def margin_balance(self) -> float:
        """Wallet balance + total unrealized PnL."""
        return self.wallet_balance + self.unrealized_pnl_total

    @property
    def available_balance(self) -> float:
        """Margin balance - total margin used by open positions."""
        used = sum(p.margin_used for p in self.positions.values() if p.status == "OPEN")
        return max(0.0, self.margin_balance - used)

    @property
    def total_equity(self) -> float:
        """Same as margin_balance for this simple model."""
        return self.margin_balance

    # -- Position Management --

    def get_open_position(self, symbol: str) -> Optional[Position]:
        pos = self.positions.get(symbol)
        if pos and pos.status == "OPEN":
            return pos
        return None

    def can_open_position(self, symbol: str, signal: Signal) -> Tuple[bool, str]:
        """
        Check if a new position can be opened.
        Returns (can_open, reason).
        """
        if signal == Signal.NEUTRAL:
            return False, "Signal is NEUTRAL"

        existing = self.get_open_position(symbol)
        if existing:
            existing_signal = Signal.LONG if existing.side == PositionSide.LONG else Signal.SHORT
            if existing_signal == signal:
                return False, f"Already LONG on {symbol}; same-direction signal ignored"
            else:
                return False, f"Already SHORT on {symbol}; opposite-direction signal ignored (close manually or via SL/TP)"

        if self.available_balance <= 0:
            return False, "No available balance"

        return True, "OK"

    def open_position(
        self,
        symbol: str,
        signal: Signal,
        entry_price: float,
        mark_price: float = None,
    ) -> Optional[Position]:
        """
        Open a new futures position using 50% of available equity at 10x leverage.
        """
        can_open, reason = self.can_open_position(symbol, signal)
        if not can_open:
            logger.info(f"[OPEN BLOCKED] {symbol}: {reason}")
            return None

        # Capital allocation
        capital_to_use = self.available_balance * self.equity_utilization
        if capital_to_use <= 0:
            logger.warning("No capital to allocate")
            return None

        # With leverage, notional = capital * leverage
        notional = capital_to_use * self.leverage
        quantity = notional / entry_price
        margin_used = capital_to_use  # notional / leverage

        side = PositionSide.LONG if signal == Signal.LONG else PositionSide.SHORT

        # PnL targets in absolute USDT terms (relative to margin used)
        pnl_target = margin_used * self.pnl_target_pct
        catastrophic_sl = margin_used * self.catastrophic_sl_pct  # negative number

        position = Position(
            symbol=symbol,
            side=side,
            entry_price=entry_price,
            quantity=quantity,
            notional=notional,
            margin_used=margin_used,
            leverage=self.leverage,
            open_time=int(time.time() * 1000),
            pnl_target=pnl_target,
            catastrophic_sl=catastrophic_sl,
        )

        if mark_price:
            position.update_pnl(mark_price)

        self.positions[symbol] = position
        logger.info(
            f"[POSITION OPENED] {symbol} {side.value} | "
            f"Qty={quantity:.6f} @ {entry_price:.2f} | "
            f"Notional={notional:.2f} USDT | Margin={margin_used:.2f} USDT | "
            f"Target=+{pnl_target:.2f} | CatSL={catastrophic_sl:.2f}"
        )
        self._save_state()
        return position

    def close_position(
        self,
        symbol: str,
        close_price: float,
        reason: str = "manual",
    ) -> Optional[Position]:
        """Close an open position and realize PnL."""
        pos = self.get_open_position(symbol)
        if not pos:
            logger.warning(f"No open position on {symbol} to close")
            return None

        pos.update_pnl(close_price)
        realized = pos.unrealized_pnl
        pos.realized_pnl = realized
        pos.status = "CLOSED"
        pos.close_time = int(time.time() * 1000)
        pos.close_price = close_price
        pos.close_reason = reason

        # Update wallet
        self.wallet_balance += realized
        self.realized_pnl_total += realized
        self.unrealized_pnl_total -= pos.unrealized_pnl  # remove from unrealized

        self.position_history.append(pos.to_dict())
        del self.positions[symbol]

        logger.info(
            f"[POSITION CLOSED] {symbol} {pos.side.value} | "
            f"Close={close_price:.2f} | Realized PnL={realized:.2f} USDT | Reason={reason}"
        )
        self._save_state()
        return pos

    def update_positions(self, mark_prices: Dict[str, float]):
        """
        Update unrealized PnL for all open positions and check SL/TP.
        mark_prices: dict of symbol -> current mark price
        """
        for symbol, pos in list(self.positions.items()):
            if pos.status != "OPEN":
                continue

            mark = mark_prices.get(symbol)
            if mark is None:
                continue

            pos.update_pnl(mark)
            pnl = pos.unrealized_pnl

            # Check take-profit
            if pnl >= pos.pnl_target:
                self.close_position(symbol, mark, reason=f"TP_HIT (+{pnl:.2f} USDT)")
                continue

            # Check catastrophic stop-loss (-50% of margin)
            if pnl <= pos.catastrophic_sl:
                self.close_position(symbol, mark, reason=f"CATASTROPHIC_SL ({pnl:.2f} USDT)")
                continue

        # Recompute total unrealized
        self.unrealized_pnl_total = sum(
            p.unrealized_pnl for p in self.positions.values() if p.status == "OPEN"
        )

    def get_portfolio_summary(self) -> dict:
        """Return a snapshot of the wallet state."""
        open_positions = [p.to_dict() for p in self.positions.values() if p.status == "OPEN"]
        return {
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "wallet_balance": round(self.wallet_balance, 4),
            "unrealized_pnl_total": round(self.unrealized_pnl_total, 4),
            "realized_pnl_total": round(self.realized_pnl_total, 4),
            "margin_balance": round(self.margin_balance, 4),
            "available_balance": round(self.available_balance, 4),
            "total_equity": round(self.total_equity, 4),
            "open_positions_count": len(open_positions),
            "open_positions": open_positions,
            "position_history_count": len(self.position_history),
        }

    def print_summary(self):
        summary = self.get_portfolio_summary()
        print("\n" + "=" * 60)
        print("  FUTURES WALLET SUMMARY")
        print("=" * 60)
        print(f"  Wallet Balance      : {summary['wallet_balance']:.4f} USDT")
        print(f"  Unrealized PnL      : {summary['unrealized_pnl_total']:.4f} USDT")
        print(f"  Realized PnL        : {summary['realized_pnl_total']:.4f} USDT")
        print(f"  Margin Balance      : {summary['margin_balance']:.4f} USDT")
        print(f"  Available Balance   : {summary['available_balance']:.4f} USDT")
        print(f"  Open Positions      : {summary['open_positions_count']}")
        if summary["open_positions"]:
            for p in summary["open_positions"]:
                print(f"    - {p['symbol']} {p['side']} | "
                      f"Entry={p['entry_price']:.2f} | "
                      f"U-PnL={p['unrealized_pnl']:.4f} ({p['unrealized_pnl']/p['margin_used']*100:.2f}%)")
        print("=" * 60 + "\n")

    # -- Persistence --

    def _save_state(self):
        state = {
            "wallet_balance": self.wallet_balance,
            "realized_pnl_total": self.realized_pnl_total,
            "positions": {s: p.to_dict() for s, p in self.positions.items()},
            "position_history": self.position_history,
        }
        with open(self.state_file, "w") as f:
            json.dump(state, f, indent=2, default=str)

    def _load_state(self):
        if not self.state_file.exists():
            return
        try:
            with open(self.state_file, "r") as f:
                state = json.load(f)
            self.wallet_balance = state.get("wallet_balance", self.wallet_balance)
            self.realized_pnl_total = state.get("realized_pnl_total", 0.0)
            self.positions = {
                s: Position.from_dict(d)
                for s, d in state.get("positions", {}).items()
            }
            self.position_history = state.get("position_history", [])
            logger.info(f"Loaded wallet state from {self.state_file}")
        except Exception as e:
            logger.warning(f"Failed to load state: {e}")

    def reset(self):
        """Clear all state and reset to initial balance."""
        self.positions.clear()
        self.position_history.clear()
        self.wallet_balance = 10_000.0
        self.unrealized_pnl_total = 0.0
        self.realized_pnl_total = 0.0
        if self.state_file.exists():
            self.state_file.unlink()
        logger.info("Wallet state reset")


