class BinanceDataFeed:
    """Fetches market data from Binance USD-M Futures REST API."""

    def __init__(self, base_url: str = BINANCE_FAPI_BASE):
        self.base_url = base_url.rstrip("/")
        self.session = requests.Session()
        self.session.headers.update({
            "Accept": "application/json",
            "User-Agent": "FuturesTrader/1.0",
        })

    def _get(self, endpoint: str, params: dict = None) -> dict:
        url = f"{self.base_url}/fapi/{endpoint}"
        try:
            resp = self.session.get(url, params=params, timeout=15)
            resp.raise_for_status()
            return resp.json()
        except requests.HTTPError as e:
            status = e.response.status_code if e.response is not None else None
            if status == 418:
                logger.critical("Binance IP ban (418) detected. Sleeping 120s before retry.")
                time.sleep(120)
            elif status == 429:
                logger.warning("Binance rate limit (429) detected. Sleeping 60s before retry.")
                time.sleep(60)
            raise
        except requests.RequestException as e:
            logger.error(f"Request failed: {e}")
            raise

    def get_klines(
        self,
        symbol: str,
        interval: str = "1h",
        limit: int = 150,
        start_time: int = None,
        end_time: int = None,
    ) -> pd.DataFrame:
        """
        Fetch OHLCV klines and return a pandas DataFrame.
        Columns: open_time, open, high, low, close, volume, close_time,
                 quote_volume, trades, taker_buy_base, taker_buy_quote, ignore
        """
        params = {
            "symbol": symbol.upper(),
            "interval": interval,
            "limit": limit,
        }
        if start_time:
            params["startTime"] = start_time
        if end_time:
            params["endTime"] = end_time

        data = self._get("v1/klines", params)
        if not data:
            raise ValueError("No kline data returned")

        df = pd.DataFrame(data, columns=[
            "open_time", "open", "high", "low", "close", "volume",
            "close_time", "quote_volume", "trades",
            "taker_buy_base", "taker_buy_quote", "ignore",
        ])
        numeric_cols = ["open", "high", "low", "close", "volume",
                        "quote_volume", "taker_buy_base", "taker_buy_quote"]
        df[numeric_cols] = df[numeric_cols].astype(float)
        df["open_time"] = pd.to_datetime(df["open_time"], unit="ms", utc=True)
        df["close_time"] = pd.to_datetime(df["close_time"], unit="ms", utc=True)
        return df

    def get_mark_price(self, symbol: str) -> float:
        """Get current mark price for a symbol."""
        data = self._get("v1/premiumIndex", {"symbol": symbol.upper()})
        return float(data["markPrice"])

    def get_exchange_info(self) -> dict:
        """Get exchange info including symbol filters and leverage brackets."""
        return self._get("v1/exchangeInfo")

    def get_server_time(self) -> int:
        """Get Binance server time in milliseconds."""
        return self._get("v1/time")["serverTime"]


