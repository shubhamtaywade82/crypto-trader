"""
crypto_trader.websocket — Real-Time Binance Futures WebSocket Client
======================================================================
Streams:
    • @markPrice — mark price + funding rate (every 1s or 3s)
    • @kline_1h / @kline_4h — candle updates
    • @bookTicker — best bid/ask (LTP for entries/exits)
    • @aggTrade — recent trades for volume/sentiment

Architecture:
    - Single WebSocket connection per symbol
    - Async thread for non-blocking reception
    - Thread-safe ring buffer for latest data
    - Auto-reconnect with exponential backoff
    - Heartbeat/ping-pong handling

Author: Generated by Kimi K2.6
"""

