    def _mr_check_sma_exit(self, data: dict, pos) -> bool:
        """
        Check whether price has reverted to the SMA (mean-reversion exit).

        Called every signal tick when strategy_mode == "mean_reversion" and a
        position is open. Returns True if the position was closed.
        """
        if self.playbook_mr is None:
            return False
        try:
            # Use pre-fetched MR dataframe (from _fetch_market_data) or fall back
            df_mr = data.get("df_mr")
            if df_mr is None:
                mr_tf = self.playbook_mr.timeframe
                _baseline_map = {
                    "15m": data.get("df_15m"),
                    "5m": data.get("df_5m"),
                    "1h": data.get("df_1h"),
                    "4h": data.get("df_4h"),
                }
                df_mr = _baseline_map.get(mr_tf)
            if df_mr is None:
                try:
                    df_mr = self.data_feed.get_klines(
                        self.symbol, self.playbook_mr.timeframe,
                        limit=self.playbook_mr.sma_period + 10
                    )
                except Exception as e:
                    logger.warning("[MR EXIT] Could not fetch klines: %s", e)
                    return False

            exit_reason = self.playbook_mr.check_sma_exit(df_mr, pos.side)
            if exit_reason is None:
                return False

            mark = data["mark_price"]
            self.wallet.close_position(self.symbol, float(mark), reason=exit_reason)
            logger.info(
                "[MR EXIT] %s %s position closed — mean reverted. mark=%.4f",
                self.symbol, pos.side.value, mark,
            )
            if self.event_bus:
                from .events import TradeClosedEvent
                # TradeClosedEvent is emitted by wallet.close_position via the
                # event_hook chain; no need to re-emit here.
            return True

        except Exception as exc:
            logger.warning("[MR EXIT] SMA exit check failed for %s: %s", self.symbol, exc)
            return False

    def _evaluate_entry_mr(
        self,
        data: dict,
        mark_price: float,
        funding_rate: float,
        taker_ratio: float,
        regime_ctx,
    ) -> None:
        """
        Entry evaluation path for strategy_mode == "mean_reversion".

        Implements the SRD/PRD specification:
        - Computes SMA(mr_sma_period) on last CLOSED candle of mr_timeframe.
        - Opens LONG  when close <= SMA * (1 - entry_band)   [oversold]
        - Opens SHORT when close >= SMA * (1 + entry_band)   [overbought]
        - Funding-rate guard blocks entries when funding is extreme.
        - All risk-manager guards (daily limits, drawdown, kill-switch) are
          applied by the calling layer before this method is called.
        - Works for any symbol in the WATCHLIST (symbol-agnostic).
        """
        if self.playbook_mr is None:
            return

        # Resolve the configured MR timeframe DataFrame — use pre-fetched
        # data["df_mr"] if available (set by _fetch_market_data), falling back
        # to baseline frames or a fresh REST call for non-standard timeframes.
        df_mr = data.get("df_mr")
        if df_mr is None:
            mr_tf = self.playbook_mr.timeframe
            _baseline_map = {
                "15m": data.get("df_15m"),
                "5m":  data.get("df_5m"),
                "1h":  data.get("df_1h"),
                "4h":  data.get("df_4h"),
            }
            df_mr = _baseline_map.get(mr_tf)
        if df_mr is None:
            try:
                df_mr = self.data_feed.get_klines(
                    self.symbol, self.playbook_mr.timeframe,
                    limit=self.playbook_mr.sma_period + 10
                )
            except Exception as e:
                logger.warning("[MR ENTRY] Could not fetch klines for %s: %s", self.symbol, e)
                return

        setup = self.playbook_mr.evaluate(df_mr)
        if not setup:
            logger.debug("[MR ENTRY] No signal this tick for %s", self.symbol)
            return

        logger.info(
            "[MR SIGNAL] %s | %s | %s",
            self.symbol, setup["side"].value, setup["reason"]
        )

        # Funding-rate extreme guard (PRD §7)
        _funding_extreme = self.cfg.funding_extreme_threshold if self.cfg else FUNDING_EXTREME
        if (
            (setup["side"] == PositionSide.LONG and funding_rate > _funding_extreme)
            or (setup["side"] == PositionSide.SHORT and funding_rate < -_funding_extreme)
        ):
            logger.info(
                "[MR BLOCKED] %s — funding extreme %+.4f%% (threshold %.4f%%)",
                self.symbol, funding_rate * 100, _funding_extreme * 100,
            )
            return

        dynamic_threshold = self.adaptive_threshold.get_threshold()

        # Mean-reversion signal score is treated as the authoritative technical
        # score (no LLM fusion for now — keeps execution deterministic as the
        # PRD specifies).  Passes directly to _execute_entry.
        self._execute_entry(EntryContext(
            setup=setup,
            final_score=setup["score"],
            llm_weight=0.0,
            explanation=f"MeanReversion SMA{self.playbook_mr.sma_period} signal",
            mark_price=mark_price,
            funding_rate=funding_rate,
            oi_delta=0.0,
            taker_ratio=taker_ratio,
            tech_score=setup["score"],
            regime=None,
            regime_score=1.0,
            advice=None,
            dynamic_threshold=dynamic_threshold,
            regime_ctx=regime_ctx,
        ))

    # ─── Position update helpers ────────────────────────────────────────────

    def _update_open_position(self, data: dict, regime, session_ctx):
        """Update an open position if one exists (step 5.5 — AI/regime reversal exits)."""
        pos = self.wallet.get_open_position(self.symbol)
        if pos:
            # MR mode: check for SMA-touch exit before any other logic
            _mr_mode = self.cfg and getattr(self.cfg, "strategy_mode", "legacy") == "mean_reversion"
            if _mr_mode and self._mr_check_sma_exit(data, pos):
                return  # position closed by SMA reversion; skip further management

            # ST2 mode: check for Supertrend flip exit before normal SL/TP logic
            _st2_mode = self.cfg and getattr(self.cfg, "strategy_mode", "legacy") == "supertrend2"
            if _st2_mode and self._st2_check_flip_exit(data, pos):
                return  # position closed by flip; skip further position management

            df_1h = data["df_1h"]
            mark_price = data["mark_price"]
            df_1h["ema9"] = compute_ema(df_1h["close"], 9)
            ema9_val = df_1h["ema9"].iloc[-1]
            ema9_1h = float(ema9_val) if pd.notna(ema9_val) else None
            candle_close_time = int(df_1h["close_time"].iloc[-1].timestamp() * 1000)

            advice = self.advisor.get_last_advice() if (self.use_llm and self.advisor) else None
            current_llm_advice = advice.to_dict() if advice else None

            self.wallet.update_positions(
                self.symbol,
                mark_price,
                candle_close_time,
                ema9_1h,
                current_llm_advice=current_llm_advice,
                current_regime=regime.value if regime else None,
            )

    def _evaluate_and_enter(self, data: dict, regime, regime_score, df_4h, rvol, adx_val,
                            regime_ctx, session_ctx, structure, structure_ltf):
        """Perform risk check, update open position, then evaluate entry if no position open."""
        mark_price = data["mark_price"]
        funding_rate = data["funding_rate"]
        taker_ratio = data["taker_ratio"]
        df_1h = data["df_1h"]
        df_15m = data["df_15m"]

        # 5. Risk check
        self.risk_manager.update_peak_balance(self.wallet.margin_balance)
        # Assuming initial balance for daily drawdown is the wallet balance minus daily PnL
        initial_daily_balance = float(self.wallet.wallet_balance) - self.risk_manager.daily_pnl
        can_trade, risk_reason = self.risk_manager.can_trade(
            current_balance=self.wallet.margin_balance,
            initial_daily_balance=initial_daily_balance
        )
        if not can_trade:
            if not getattr(self, "_halt_published", False):
                if self.event_bus:
                    from .events import RiskHaltEvent
                    self.event_bus.publish(RiskHaltEvent(
                        reason=risk_reason,
                        daily_pnl=float(self.wallet.realized_pnl_total),
                        trades_today=self.risk_manager.daily_count
                    ))
                self._halt_published = True
            logger.info(f"[RISK] {risk_reason}")
            return
        self._halt_published = False

        # 5.5 Update position if open (to check AI and regime reversal exits)
        self._update_open_position(data, regime, session_ctx)

        # 6. Evaluate entry if no open position
        if not self.wallet.get_open_position(self.symbol) and can_trade:
            _st2_mode = self.cfg and getattr(self.cfg, "strategy_mode", "legacy") == "supertrend2"
            _mr_mode  = self.cfg and getattr(self.cfg, "strategy_mode", "legacy") == "mean_reversion"

            try:
                if _st2_mode:
                    # ── Supertrend2 path ──────────────────────────────────────
                    # Bypass legacy regime routing, profile regime filter, and LLM.
                    # The Supertrend direction flip is the sole entry gate.
                    self._evaluate_entry_st2(
                        data, mark_price, funding_rate, taker_ratio, regime_ctx
                    )
                elif _mr_mode:
                    # ── Mean Reversion path ───────────────────────────────────
                    # SMA-band signal; funding-rate guard applied inside.
                    # Symbol-agnostic: works for all WATCHLIST symbols.
                    self._evaluate_entry_mr(
                        data, mark_price, funding_rate, taker_ratio, regime_ctx
                    )
                else:
                    # ── Legacy multi-playbook path ────────────────────────────
                    # Block entry when regime forbids it
                    if not regime_ctx.allows_new_entries():
                        logger.info(
                            "[REGIME-BLOCK] No entry — extended regime is %s",
                            regime_ctx.extended.value,
                        )
                        return

                    # Profile-based regime filter
                    if self.cfg and self.cfg.allowed_regimes:
                        if regime_ctx.extended.value not in self.cfg.allowed_regimes:
                            logger.info(
                                "[PROFILE-BLOCK] %s regime not allowed by '%s' profile",
                                regime_ctx.extended.value, self.cfg.trading_profile,
                            )
                            return

                    latest_adx = df_4h["adx"].iloc[-1] if "adx" in df_4h.columns else None
                    self._evaluate_entry(
                        df_1h, df_4h, df_15m, regime, regime_score, mark_price,
                        funding_rate, 0.0, taker_ratio, structure=structure,
                        adx_1h=latest_adx, regime_ctx=regime_ctx,
                        session_ctx=session_ctx, structure_ltf=structure_ltf,
                    )

            except Exception as e:
                # Distinguish a benign pre-fill venue REJECTION from an ambiguous
                # mid-entry failure that could orphan a live position.
                #
                # A definitive 4xx order rejection (e.g. min-notional, bad params,
                # insufficient balance) is raised by place_order BEFORE any fill is
                # booked — no position exists, so halting all trading is wrong.
                # Skip this tick and keep trading. Ambiguous failures (5xx /
                # timeout / anything not provably pre-fill) still HALT + reconcile
                # because the order MIGHT be live.
                if self._is_benign_entry_rejection(e):
                    logger.warning(
                        "[ENTRY SKIP] %s — venue rejected order pre-fill (no position "
                        "opened), skipping tick: %s", self.symbol, e,
                    )
                    if self.event_bus:
                        from .events import SignalRejectedEvent
                        self.event_bus.publish(SignalRejectedEvent(
                            symbol=self.symbol, reason=f"venue_rejected: {e}",
                        ))
                    return
                # An exception mid-entry could leave an unmanaged live position.
                # Fail safe: HALT and trip the kill switch.
                logger.critical("[ENTRY FAILURE] %s — halting and reconciling: %s", self.symbol, e, exc_info=True)
                self._halted = True
                if getattr(self, "risk_manager", None) is not None:
                    self.risk_manager.trigger_kill_switch(f"entry failure: {e}")
                if self.cfg and self.cfg.is_live:
                    try:
                        from . import safe_mode
                        safe_mode.trip_halt(f"entry failure for {self.symbol}: {e}")
                    except Exception:
                        pass
                if self.event_bus:
                    from .events import SystemFailureEvent
                    self.event_bus.publish(SystemFailureEvent(component="entry", error=str(e)))

    @staticmethod
    def _is_benign_entry_rejection(exc: Exception) -> bool:
        """True when *exc* is a definitive venue order rejection raised BEFORE any
        fill could be booked — safe to skip without halting.

        Only a CoinDCX 4xx (client/validation error: min-notional, bad params,
        insufficient balance, etc.) qualifies. The CoinDCX client raises 429/5xx/
        timeout on non-idempotent calls as 'ambiguous — reconcile against venue'
        (status_code None or >=500), which must still trip the halt."""
        from .exchanges.coindcx_client import CoinDCXError
        if not isinstance(exc, CoinDCXError):
            return False
        sc = getattr(exc, "status_code", None)
        return isinstance(sc, int) and 400 <= sc < 500 and sc != 429

    # StrategyRouter is lazily built on first use and cached.
    # Use build_legacy_router() to customise the regime → playbook map.
    _strategy_router: Optional[StrategyRouter] = None

    def _get_strategy_router(self) -> StrategyRouter:
        if self._strategy_router is None:
            self._strategy_router = build_legacy_router()
        return self._strategy_router

    def _evaluate_entry(self, df_1h, df_4h, df_15m, regime, regime_score, mark_price,
                        funding_rate, oi_delta, taker_ratio, structure=None, adx_1h=None,
                        regime_ctx: Optional[RegimeContext] = None,
                        session_ctx=None, structure_ltf=None):
        """Evaluate entry signals and execute via WebSocket LTP.

        Score-based best-of selection is delegated to :class:`StrategyRouter`.
        This method is responsible only for:
          - building the dict of playbook evaluator lambdas,
          - post-selection correlation and funding-rate vetoes,
          - dispatching to _execute_entry.
        """
        playbook_evaluators = {
            "playbook_ares":  lambda: self.playbook_ares.evaluate(df_15m, adx_1h=adx_1h),
            "playbook_volx":  lambda: self.playbook_volx.evaluate(df_15m, adx_1h=adx_1h),
            "playbook_a":     lambda: self.playbook_a.evaluate(df_1h, regime, structure=structure),
            "playbook_b":     lambda: self.playbook_b.evaluate(df_1h, df_4h, regime, structure=structure),
            "playbook_sweep": lambda: self.playbook_sweep.evaluate(
                df_1h, df_15m, structure, structure_ltf, regime=regime),
        }

        result: Optional[RouterResult] = self._get_strategy_router().select(
            regime_ctx=regime_ctx,
            playbook_evaluators=playbook_evaluators,
            advisor=self.advisor,
            dynamic_threshold=self.adaptive_threshold.get_threshold(),
            regime=regime,
            regime_score=regime_score,
        )
        if result is None:
            return

        setup = result.setup

        # Correlation check (wallet-state dependent — stays here, not in router)
        active_positions = {
            s: p.to_dict()
            for s, p in self.wallet.positions.items()
            if p.status == "OPEN"
        }
        ok, corr_reason = self.risk_manager.check_correlation(
            self.symbol, setup["side"].value, active_positions
        )
        if not ok:
            logger.info("[BLOCKED] %s", corr_reason)
            return

        if self.advisor and result.advice:
            logger.info("[FUSION] %s | final=%.2f", result.explanation, result.final_score)

        # Funding-rate extreme gate
        _funding_extreme = self.cfg.funding_extreme_threshold if self.cfg else FUNDING_EXTREME
        if (
            (setup["side"] == PositionSide.LONG and funding_rate > _funding_extreme)
            or (setup["side"] == PositionSide.SHORT and funding_rate < -_funding_extreme)
        ):
            logger.info(
                "[BLOCKED] Funding extreme for %s: %+.4%% (threshold=%.2%%)",
                setup["side"].value, funding_rate, _funding_extreme,
            )
            return

        self._execute_entry(EntryContext(
            setup=setup,
            final_score=result.final_score,
            llm_weight=result.llm_weight,
            explanation=result.explanation,
            mark_price=mark_price,
            funding_rate=funding_rate,
            oi_delta=oi_delta,
            taker_ratio=taker_ratio,
            tech_score=result.tech_score,
            regime=regime,
            regime_score=regime_score,
            advice=result.advice,
            dynamic_threshold=result.dynamic_threshold,
            regime_ctx=regime_ctx,
        ))

    def _coindcx_market_data(self):
        if self._coindcx_md is None:
            from .exchanges.coindcx_market_data import CoinDCXMarketData
            self._coindcx_md = CoinDCXMarketData()
        return self._coindcx_md

    def _basis_guard(self, side, binance_mark: float):
        """Cross-venue basis guard (F3).

        Signals fire on Binance price but fills happen on CoinDCX. Reject the
        entry when the venues diverge beyond the configured threshold. Returns
        ``(allowed, basis)``. If CoinDCX data is unavailable, skip the guard
        (don't block trading on a missing fallback feed).
        """
        cfg = self.cfg
        if cfg is None or not getattr(cfg, "basis_guard_enabled", False) or binance_mark <= 0:
            return True, 0.0
        try:
            cdcx_mark = self._coindcx_market_data().get_mark_price(self.symbol)
        except Exception as e:
            logger.warning("[BASIS] CoinDCX mark unavailable (%s); skipping guard", e)
            return True, 0.0
        if cdcx_mark <= 0:
            return True, 0.0
        basis = (cdcx_mark - binance_mark) / binance_mark
        if abs(basis) > cfg.max_cross_venue_basis:
            logger.warning(
                f"[BASIS BLOCKED] {self.symbol} basis {basis:+.4%} exceeds "
                f"{cfg.max_cross_venue_basis:.2%} (binance={binance_mark:.4f} coindcx={cdcx_mark:.4f})"
            )
            if self.event_bus:
                from .events import SignalRejectedEvent
                self.event_bus.publish(SignalRejectedEvent(
                    symbol=self.symbol,
                    reason=f"cross-venue basis {basis:+.4%} > {cfg.max_cross_venue_basis:.2%}",
                ))
            return False, basis
        return True, basis

    def _execute_entry(self, ctx_or_setup, final_score=None, llm_weight=None,
                      explanation=None, mark_price=None, funding_rate=None,
                      oi_delta=None, taker_ratio=None, tech_score=None,
                      regime=None, regime_score=None, advice=None,
                      dynamic_threshold=None, regime_ctx=None):
        """Execute entry using real-time WebSocket prices.

        Accepts either an EntryContext as the sole positional argument (new API)
        or the legacy keyword-argument form (kept for backwards compatibility).
        """
        if isinstance(ctx_or_setup, EntryContext):
            ctx = ctx_or_setup
        else:
            ctx = EntryContext(
                setup=ctx_or_setup,
                final_score=final_score,
                llm_weight=llm_weight if llm_weight is not None else 0.0,
                explanation=explanation if explanation is not None else "",
                mark_price=mark_price if mark_price is not None else 0.0,
                funding_rate=funding_rate if funding_rate is not None else 0.0,
                oi_delta=oi_delta if oi_delta is not None else 0.0,
                taker_ratio=taker_ratio if taker_ratio is not None else 1.0,
                tech_score=tech_score if tech_score is not None else 0.0,
                regime=regime,
                regime_score=regime_score if regime_score is not None else 0.0,
                advice=advice,
                dynamic_threshold=dynamic_threshold if dynamic_threshold is not None else 0.75,
                regime_ctx=regime_ctx,
            )

        setup = ctx.setup
        final_score = ctx.final_score
        llm_weight = ctx.llm_weight
        explanation = ctx.explanation
        mark_price = ctx.mark_price
        funding_rate = ctx.funding_rate
        oi_delta = ctx.oi_delta
        taker_ratio = ctx.taker_ratio
        tech_score = ctx.tech_score
        regime = ctx.regime
        regime_score = ctx.regime_score
        advice = ctx.advice
        dynamic_threshold = ctx.dynamic_threshold
        regime_ctx = ctx.regime_ctx

        # A1: never enter on stale data. If the WS feed has no fresh price within
        # the staleness budget, veto the entry rather than fall back to a possibly
        # seconds-old price. (Exits are separately gated in ws_pm.)
        stale_ms = self.cfg.feed_stale_ms if self.cfg else 15000
        if not self.ws_feed.is_fresh(stale_ms):
            age = self.ws_feed.data_age_ms()
            logger.warning("[ENTRY] WS feed stale (age=%sms > %dms) — vetoing entry", age, stale_ms)
            return

        # Get current LTP and spread from WebSocket
        ltp = self.ws_feed.get_ltp()
        mid = self.ws_feed.get_mid_price()
        spread = self.ws_feed.get_spread()

        if ltp <= 0 or mid <= 0:
            logger.warning("[ENTRY] WebSocket LTP/mid unavailable (ltp=%.4f mid=%.4f) — vetoing entry", ltp, mid)
            return

        # Slippage estimate: if spread > 0.1%, log warning
        spread_pct = spread / mid * 100 if mid > 0 else 0
        if spread_pct > 0.1:
            logger.warning(f"[ENTRY] Wide spread: {spread_pct:.3f}% | bid={self.ws_feed.data.best_bid:.2f} ask={self.ws_feed.data.best_ask:.2f}")

        # F3: cross-venue basis guard — reject if Binance and CoinDCX diverge.
        allowed, _basis = self._basis_guard(setup["side"], mid if mid > 0 else mark_price)
        if not allowed:
            return

        # Adjust entry price to use mid price (fairer than LTP which can be stale).
        # F3: nudge the trigger toward the fill venue by the basis buffer so risk
        # sizing reflects the price we'll actually fill on at CoinDCX.
        entry_price = mid
        buf = self.cfg.entry_basis_buffer if (self.cfg and getattr(self.cfg, "basis_guard_enabled", False)) else 0.0
        if buf:
            entry_price = mid * (1 + buf) if setup["side"] == PositionSide.LONG else mid * (1 - buf)

        # Re-anchor the PLAYBOOK's stop/target to the actual fill entry.
        # The playbook computed sl/tp off its signal price; the real entry (mid +
        # basis buffer) differs slightly, so we preserve the playbook's
        # proportional stop distance rather than discarding it for a flat default.
        is_long = setup["side"] == PositionSide.LONG
        pb_entry = float(setup.get("entry_price") or 0)
        default_sl_pct, default_tp_pct = DEFAULT_SL_PCT, DEFAULT_TP1_PCT

        def _reanchor(level_price, fallback_pct, is_stop):
            """Map a playbook level to the actual entry, keeping its ratio."""
            if pb_entry > 0 and level_price and float(level_price) > 0:
                return entry_price * (float(level_price) / pb_entry)
            # No usable playbook level — fall back to a flat default.
            if is_stop:
                return entry_price * (1 - fallback_pct) if is_long else entry_price * (1 + fallback_pct)
            return entry_price * (1 + fallback_pct) if is_long else entry_price * (1 - fallback_pct)

        sl = _reanchor(setup.get("sl_price"), default_sl_pct, is_stop=True)

        # Update setup with actual entry price + re-anchored stop.
        setup["entry_price"] = entry_price
        setup["sl_price"] = sl
        if "tp_price" in setup:
            setup["tp_price"] = _reanchor(setup.get("tp_price"), default_tp_pct, is_stop=False)
        else:
            for tp_level in setup.get("tp_levels", []):
                lvl_default = 0.010 if tp_level.get("label") == "TP1" else 0.020
                tp_level["price"] = _reanchor(tp_level.get("price"), lvl_default, is_stop=False)

        # Representative TP for events/logging (first target, or single tp_price).
        tp = setup.get("tp_price")
        if tp is None:
            _levels = setup.get("tp_levels", [])
            tp = _levels[0]["price"] if _levels else entry_price

        # Risk-based sizing from stop distance (2% risk per trade, scaled by this
        # engine's share of a shared wallet to avoid multi-symbol over-allocation).
        stop_distance = abs(entry_price - setup["sl_price"])
        _risk_pct = Decimal(str(self.cfg.risk_per_trade_pct)) if self.cfg else Decimal("0.02")
        risk_budget = self.wallet.margin_balance * _risk_pct * Decimal(str(self.risk_budget_fraction))
        size_multiplier = min(final_score / dynamic_threshold, 1.0)
        # Apply regime-based size scalar (e.g. 1.25× for TREND_EXPANSION, 0.5× for LOW_VOL_CHOP)
        if regime_ctx is not None and regime_ctx.size_multiplier != 1.0:
            size_multiplier *= regime_ctx.size_multiplier
            logger.debug(
                f"[SIZING] regime={regime_ctx.extended.value} size_x={regime_ctx.size_multiplier:.2f} "
                f"→ combined_multiplier={size_multiplier:.3f}"
            )
        risk_budget *= Decimal(str(size_multiplier))
        stop_distance_dec = Decimal(str(stop_distance))
        quantity = (risk_budget / stop_distance_dec) if stop_distance_dec > 0 else Decimal("0")

        trade_id = str(uuid.uuid4())[:8]

        # Without a stop we cannot size at all → hard skip (covers the
        # quantity<=0-because-stop_distance==0 case). A tiny risk_budget that
        # yields qty<=0 with a VALID stop is handled by the bump-to-minimum
        # logic below, not skipped here.
        if stop_distance_dec <= 0:
            logger.warning("[ENTRY] computed quantity <= 0 (stop_distance=%s); skipping", stop_distance)
            return

        # ── Bump-to-minimum sizing ───────────────────────────────────────────
        # On a tiny account, risk-based sizing (risk_per_trade_pct × 1/N) can
        # produce a notional below CoinDCX's venue minimum (or a quantity that
        # rounds to ~0), so the order would be rejected outright. Per operator
        # decision: bump such orders UP to the smallest venue-legal size when
        # margin allows (accepting >target risk on this trade), and skip cleanly
        # if even that minimum can't be afforded. The bumped quantity is computed
        # HERE so it flows into the margin/liq/leverage validations below AND into
        # downstream order placement (no validate-one/place-another mismatch).
        entry_price_dec = Decimal(str(entry_price))
        exec_eng = getattr(self.wallet, "execution_engine", None)
        if exec_eng is not None and hasattr(exec_eng, "mapper"):
            try:
                spec = exec_eng.mapper.get_spec(self.symbol)
                min_n = Decimal(str(spec.min_notional))
                min_q = Decimal(str(spec.min_quantity))
                cur_notional = quantity * entry_price_dec
                if quantity < min_q or cur_notional < min_n:
                    # Smallest qty satisfying BOTH min_notional and min_quantity,
                    # rounded UP to the venue quantity increment (never down — a
                    # round-down could drop us back below the minimum).
                    q_for_notional = (
                        (min_n / entry_price_dec) if entry_price_dec > 0 else min_q
                    )
                    target_qty = max(q_for_notional, min_q)
                    inc = Decimal(str(spec.quantity_increment))
                    if inc > 0:
                        steps = (target_qty / inc).to_integral_value(rounding=ROUND_UP)
                        bumped_qty = steps * inc
                    else:
                        bumped_qty = target_qty
                    # Guard against float-rounding leaving us a hair below either
                    # minimum after increment rounding.
                    while bumped_qty < min_q or (bumped_qty * entry_price_dec) < min_n:
                        bumped_qty += inc if inc > 0 else (min_q - bumped_qty)

                    bumped_notional = bumped_qty * entry_price_dec
                    # Affordability / pre-send veto: required margin must fit the
                    # margin still available after existing open positions.
                    _lev_for_afford = self.wallet.get_leverage(self.symbol) if getattr(self.wallet, "live_execution", False) else (self.cfg.leverage if self.cfg else 2)
                    required_margin = float(bumped_notional) / max(_lev_for_afford, 1)
                    margin_balance_now = float(self.wallet.margin_balance)
                    used_margin_now = sum(
                        float(p.margin_used) for p in self.wallet.positions.values()
                        if p.status == "OPEN"
                    )
                    available_margin = margin_balance_now - used_margin_now
                    if required_margin > available_margin:
                        logger.warning(
                            "[ENTRY SKIP] %s cannot afford venue minimum notional "
                            "(need ~$%.2f margin, have $%.2f); skipping",
                            self.symbol, required_margin, available_margin,
                        )
                        return

                    # Risk now exceeds the configured cap — operator MUST see this.
                    risk_now = (bumped_qty * stop_distance_dec) / self.wallet.margin_balance \
                        if self.wallet.margin_balance > 0 else Decimal("0")
                    logger.warning(
                        "[SIZING BUMP] %s risk-based notional $%.2f below venue min $%.2f "
                        "— bumping qty %s→%s (risk now ~%.3f%% of equity, exceeds target %.3f%%)",
                        self.symbol, float(cur_notional), float(min_n),
                        f"{float(quantity):.8f}", f"{float(bumped_qty):.8f}",
                        float(risk_now) * 100.0, float(_risk_pct) * 100.0,
                    )
                    quantity = bumped_qty
            except Exception as e:
                # In LIVE mode the venue enforces min-notional; without the spec we
                # cannot guarantee a legal size, so sending the risk-based qty would
                # just earn a guaranteed rejection (and churn). Skip the entry and
                # let the next tick retry once the spec is fetchable. In paper mode
                # there's no venue floor — fall back to the risk-based qty as-is.
                if self.cfg and self.cfg.is_live:
                    logger.warning(
                        "[ENTRY SKIP] %s instrument spec unavailable in live mode "
                        "(%s); cannot verify min-notional, skipping tick", self.symbol, e,
                    )
                    return
                logger.warning(f"Failed to fetch instrument spec for pre-entry validation: {e}")

        # After any bump, a still-non-positive qty means we could not size a
        # legal order (e.g. no mapper AND tiny risk_budget) → skip.
        if quantity <= 0:
            logger.warning("[ENTRY] computed quantity <= 0 (stop_distance=%s); skipping", stop_distance)
            return

        # Margin Engine Validation
        margin_balance = float(self.wallet.margin_balance)
        used_margin = sum(float(p.margin_used) for p in self.wallet.positions.values() if p.status == "OPEN")
        margin_ok, margin_msg = self.margin_engine.check_margin_utilization(used_margin, margin_balance)
        if not margin_ok:
            logger.warning(f"[ENTRY BLOCKED] Margin Utilization: {margin_msg}")
            return

        leverage_val = self.wallet.get_leverage(self.symbol) if getattr(self.wallet, "live_execution", False) else (self.cfg.leverage if self.cfg else 2)
        # Wallet uses mark-based margin: liq = entry / (1 ± 1/lev ∓ mmr)
        # This matches wallet._is_liquidation_required() so the entry gate
        # and the live liquidation check agree.
        _mmr = float(getattr(self.wallet, "maintenance_margin_ratio", 0.005))
        _inv_lev = 1.0 / max(leverage_val, 1)
        liq_price = (entry_price / (1 + _inv_lev - _mmr)
                     if is_long else
                     entry_price / (1 - _inv_lev + _mmr))
        liq_ok, liq_msg = self.margin_engine.check_liquidation_distance(
            entry_price=entry_price,
            stop_loss_price=setup["sl_price"],
            liquidation_price=liq_price,
            side=setup["side"].value
        )
        if not liq_ok:
            logger.warning(f"[ENTRY BLOCKED] Liquidation Distance: {liq_msg}")
            return

        # Leverage Engine Validation
        notional = float(quantity) * entry_price
        lev_ok, lev_msg = self.leverage_engine.validate_leverage_tier(
            requested_leverage=leverage_val,
            position_notional=notional,
            max_notional_for_tier=50000.0
        )
        if not lev_ok:
            logger.warning(f"[ENTRY BLOCKED] Leverage Tier: {lev_msg}")
            return

        # (Venue min-notional / min-quantity is enforced earlier via
        # bump-to-minimum, so the qty reaching the margin/liq/leverage checks
        # above and the placement below is already venue-legal.)

        # ── F6: Fee-adjusted expected profit gate ─────────────────────────────
        fee_gate_ok = True
        if self.cfg and getattr(self.cfg, "fee_awareness_enabled", False):
            taker_rate = float(getattr(self.wallet, "taker_fee_rate", Decimal("0.0005")))
            safety_buffer = getattr(self.cfg, "fee_safety_buffer_bps", 5.0) / 10000.0
            min_ratio = getattr(self.cfg, "min_profit_vs_fees_ratio", 1.5)

            # Conservative: assume taker on both entry and exit
            round_trip_fee = notional * taker_rate * 2.0
            total_cost = round_trip_fee + (notional * safety_buffer)

            # Expected profit to first TP (or 1% default if none set)
            tp = setup.get("tp_price")
            if not tp and setup.get("tp_levels"):
                tp = setup["tp_levels"][0].get("price")
            if tp:
                expected_profit = abs(float(tp) - entry_price) * float(quantity)
            else:
                expected_profit = notional * 0.01  # 1% default move

            if expected_profit < total_cost * min_ratio:
                logger.warning(
                    "[ENTRY BLOCKED] Fee gate: expected_profit=$%.2f < cost×ratio=$%.2f "
                    "(fees=$%.2f + buffer=$%.2f, ratio=%.1f) | notional=$%.2f",
                    expected_profit, total_cost * min_ratio,
                    round_trip_fee, notional * safety_buffer, min_ratio, notional
                )
                fee_gate_ok = False

        if not fee_gate_ok:
            return

        # ── Adaptive entry order style ────────────────────────────────────────
        # If spread is tight (< threshold) → market (speed matters).
        # If spread is wide (>= threshold) → maker_limit (fee savings worth waiting).
        cfg_style = getattr(self.cfg, "entry_order_style", "market") if self.cfg else "market"
        threshold_bps = getattr(self.cfg, "adaptive_entry_spread_threshold_bps", 2.0)
        spread_bps = spread_pct * 100.0  # convert % → bps

        if str(cfg_style).lower() == "maker_limit":
            # Global override: always use maker-limit when playbook agrees
            use_maker = str(setup.get("entry_order_style", "market")).lower() == "maker_limit"
        else:
            # Adaptive: switch to maker_limit on wide spreads
            use_maker = spread_bps >= threshold_bps
            if use_maker:
                logger.info(
                    "[ENTRY STYLE] Spread %.2f bps >= threshold %.2f bps → maker_limit",
                    spread_bps, threshold_bps
                )
        setup["entry_order_style"] = "maker_limit" if use_maker else "market"

        # Decoupled path: publish the entry as a signal. The in-process consumer
        # (shared wallet) executes it with idempotency/DLQ/PEL-recovery + a final
        # risk-gate veto, then emits TradeOpenedEvent. record_open is performed
        # exactly once by the consumer's risk gate, so we do NOT record it here.
        if self.signal_publisher is not None:
            from .execution.signal_bus import Signal
            meta = {
                "sl_price": float(setup["sl_price"]),
                "regime": regime.value if regime else "",
                "extended_regime": regime_ctx.extended.value if regime_ctx else "",
                "tech_score": float(tech_score),
                "llm_decision": "ALLOW" if final_score >= dynamic_threshold else "LLM_VETOED",
                "funding_rate": float(funding_rate),
                "oi_delta": float(oi_delta),
                "rvol": float(regime_ctx.rvol) if regime_ctx else 1.0,
                "entry_order_style": setup["entry_order_style"],
            }
            if use_maker and self.cfg:
                meta["maker_limit_timeout_s"] = float(self.cfg.maker_limit_timeout_s)
                meta["maker_limit_offset_bps"] = float(self.cfg.maker_limit_offset_bps)
                meta["maker_limit_fallback"] = str(self.cfg.maker_limit_fallback)
            if "time_stop_hours" in setup:
                meta["time_stop_hours"] = setup["time_stop_hours"]
            if "tp_price" in setup:
                meta["tp_price"] = float(setup["tp_price"])
            else:
                meta["tp_levels"] = [
                    {"price": float(t["price"]), "pct": float(t.get("pct", 1.0)),
                     "label": t.get("label", "TP")}
                    for t in setup.get("tp_levels", []) if t.get("price")
                ]
            mode = self.cfg.mode.value if self.cfg else "paper"
            self.signal_publisher.emit(Signal(
                strategy_id=f"engine_ws:{self.symbol}",
                symbol=self.symbol, side=setup["side"].value,
                quantity=float(quantity), mode=mode,
                order_type="limit" if use_maker else "market",
                price=float(entry_price), metadata=meta,
            ))
            self.adaptive_threshold.record_trade()
            logger.info("[EXECUTED→BUS] %s %s qty=%.4f @ %.4f style=%s published to execution bus",
                        self.symbol, setup["side"].value, float(quantity), float(entry_price),
                        setup["entry_order_style"])
            return

        # Direct path. For live maker-limit, acquire the passive fill lock-free
        # (never under the shared wallet lock), then book it; on a skip-fallback
        # miss, abort the entry. Paper maker-limit is simulated in open_position
        # via the setup flag. Market entries are unchanged.
        external_fill = None
        book_qty = quantity
        if use_maker and self.cfg and self.cfg.is_live:
            external_fill = self.wallet.acquire_live_entry_fill(
                self.symbol, setup["side"], quantity, Decimal(str(entry_price)),
                timeout_s=self.cfg.maker_limit_timeout_s,
                offset_bps=self.cfg.maker_limit_offset_bps,
                fallback=self.cfg.maker_limit_fallback,
            )
            if external_fill is None:
                logger.info("[MAKER-LIMIT] %s entry skipped (unfilled, fallback=skip)", self.symbol)
                return
            fq = external_fill.get("filled_quantity")
            if fq is not None:
                book_qty = Decimal(str(fq))

        pos = self.wallet.open_position(
            self.symbol,
            setup,
            entry_price,
            custom_margin=None,
            custom_quantity=book_qty,
            external_fill=external_fill,
        )

        if pos:
            self.risk_manager.record_open()
            self.adaptive_threshold.record_trade()

            if setup.get("strategy") == "mean_reversion":
                self.mr_state.record_entry(
                    side=setup["side"].value,
                    price=float(entry_price),
                    qty=float(book_qty),
                )

            # Calculate slippage
            intended = setup["entry_price"]
            actual = entry_price
            slippage = abs(actual - intended) / intended * 100 if intended > 0 else 0

            self.journal.log_open(
                trade_id=trade_id,
                symbol=self.symbol,
                regime=regime.value if regime else "",
                regime_score=regime_score,
                setup=setup,
                technical_score=tech_score,
                llm_advice=advice.to_dict() if self.advisor and advice else None,
                llm_weight=llm_weight,
                final_score=final_score,
                margin=pos.margin_used,
                notional=pos.notional,
                entry_price=entry_price,
                funding_rate=funding_rate,
                oi_delta=oi_delta,
                taker_ratio=taker_ratio,
            )

            # Cache open-side context for the outcome record built at close time.
            _has_advice = bool(self.advisor and advice)
            _llm_rationale = None
            if _has_advice:
                _factors = getattr(advice, "key_factors", None)
                if _factors:
                    _llm_rationale = "; ".join(str(f) for f in _factors)
                elif getattr(advice, "veto_reason", None):
                    _llm_rationale = advice.veto_reason
            # entry_band: per-strategy band where available (MR playbook), else cfg.
            _entry_band = setup.get("entry_band")
            if _entry_band is None and self.cfg is not None:
                _entry_band = getattr(self.cfg, "mr_entry_band", None)
            self._open_features[self.symbol] = {
                "trade_id": trade_id,
                "side": setup["side"].value,
                "opened_at": int(datetime.now(timezone.utc).timestamp() * 1000),
                "entry_price": float(entry_price),
                "quantity": float(book_qty),
                # stop loss price stashed so pnl_r can be computed at close from
                # initial_risk = |entry - stop| * quantity.
                "stop_loss_price": float(setup["sl_price"]) if setup.get("sl_price") else None,
                "regime": regime.value if regime else None,
                "regime_score": regime_score,
                # vol/extended regime descriptor (TREND_EXPANSION, LOW_VOL_CHOP, …).
                "vol_regime": regime_ctx.extended.value if regime_ctx else None,
                "funding_rate": funding_rate,
                "oi_delta": oi_delta,
                "session": regime_ctx.session_name if regime_ctx else None,
                "entry_reason": setup.get("strategy") or setup.get("playbook"),
                "llm_action": (advice.to_dict().get("bias") if _has_advice else None),
                "llm_confidence": (advice.confidence if _has_advice else None),
                "llm_rationale": _llm_rationale,
                "entry_band": float(_entry_band) if _entry_band is not None else None,
                "stop_loss_pct": setup.get("stop_loss_pct"),
                "risk_per_trade_pct": getattr(self.cfg, "risk_per_trade_pct", None) if self.cfg else None,
                "leverage": int(self.wallet.leverage),
            }

            logger.info(
                f"[EXECUTED] Trade {trade_id} | Entry={entry_price:.2f} | "
                f"Margin={pos.margin_used:.2f} | Score={final_score:.2f} | "
                f"Spread={spread_pct:.3f}% | Slippage={slippage:.3f}%"
            )

            # Publish Event for Telegram
            if self.event_bus:
                from .events import TradeOpenedEvent
                self.event_bus.publish(TradeOpenedEvent(
                    symbol=self.symbol,
                    side=setup["side"].value,
                    leverage=self.wallet.leverage,
                    entry_price=entry_price,
                    stop_loss=sl,
                    take_profit=tp,
                    margin=pos.margin_used,
                    notional=pos.notional,
                    regime=regime.value if regime else "",
                    tech_score=tech_score,
                    llm_decision="ALLOW" if final_score >= dynamic_threshold else "LLM_VETOED",
                    funding=funding_rate,
                    oi_delta=oi_delta,
                    liquidation_price=float(self.wallet.liquidation_price(pos)),
                    wallet_balance=float(self.wallet.wallet_balance),
                ))

