    def start(self):
        """Start WebSocket and position manager."""
        logger.info(f"[ENGINE] Starting WebSocket engine for {self.symbol}")
        self.ws_feed.start()
        self.ws_pm.start()
        # Wait for WebSocket to connect
        for _ in range(10):
            if self.ws_feed.is_connected():
                break
            time.sleep(0.5)
        logger.info(f"[ENGINE] WebSocket connected: {self.ws_feed.is_connected()}")

    def stop(self):
        """Gracefully stop all components."""
        logger.info("[ENGINE] Stopping...")
        self.ws_pm.stop()
        self.ws_feed.stop()
        logger.info("[ENGINE] Stopped")

    def _check_authoritative_health(self):
        """Monitor authoritative exchange metrics (margin ratio) and trigger kill switch if unsafe."""
        if not self.cfg or not self.cfg.is_live:
            return

        from .exchanges.coindcx_execution import CoinDCXExecutionEngine
        if not isinstance(self.wallet.execution_engine, CoinDCXExecutionEngine):
            return

        if not hasattr(self, "_consecutive_health_failures"):
            self._consecutive_health_failures = 0

        try:
            details = self.wallet.execution_engine.get_cross_margin_details()
            if details:
                self._consecutive_health_failures = 0
                ratio = float(details.get("margin_ratio_cross", 0) or 0)
                ok, reason = self.risk_manager.check_margin_ratio(ratio)
                if not ok:
                    logger.critical(f"[AUTHORITATIVE GUARD] {reason}")
                    self.risk_manager.trigger_kill_switch(reason)
                    self._halted = True
                    if self.event_bus:
                        from .events import SystemFailureEvent
                        self.event_bus.publish(SystemFailureEvent(component="margin_guard", error=reason))
                    # Halting only blocks NEW entries; an open position is still
                    # racing toward liquidation at this margin ratio. Flatten it.
                    try:
                        pos = self.wallet.get_open_position(self.symbol)
                        if pos:
                            mark = self.ws_feed.get_ltp() or self.ws_feed.get_mid_price()
                            if not mark or mark <= 0:
                                mark = float(pos.entry_price)
                            self.wallet.close_position(
                                self.symbol, float(mark),
                                reason="MARGIN_GUARD_FLATTEN",
                            )
                            logger.critical("[AUTHORITATIVE GUARD] flattened %s to avoid liquidation", self.symbol)
                    except Exception as e:
                        logger.error("margin-guard flatten failed for %s: %s", self.symbol, e)
        except Exception as e:
            logger.error("Authoritative health check failed: %s", e)
            self._consecutive_health_failures += 1
            if self._consecutive_health_failures >= 3 and self.wallet.get_open_position(self.symbol):
                reason = f"Authoritative health check failed consecutively {self._consecutive_health_failures} times while holding an active position: {e}"
                logger.critical(f"[AUTHORITATIVE GUARD] {reason} — triggering kill switch")
                self.risk_manager.trigger_kill_switch(reason)
                self._halted = True
                if self.event_bus:
                    from .events import SystemFailureEvent
                    self.event_bus.publish(SystemFailureEvent(component="margin_guard", error=reason))

    # ── Main Loop ──

    def run_loop(self, signal_interval_seconds: int = 300, max_iterations: int = None):
        """
        Unified Engine Loop:
            - 1s: Thread supervision & Authoritative Health (G3, G4)
            - 60s: Exchange State Reconciliation (G5, G9)
            - signal_interval: Signal evaluation & Playbook execution
        """
        self.start()
        iteration = 0
        last_signal_time = 0
        last_recon_time = 0

        try:
            while True:
                now = time.time()

                # 1s Task: G3: supervise the WS threads
                if not self._supervise_threads():
                    break

                # 1s Task: Authoritative health check (margin ratio guard)
                self._check_authoritative_health()

                # 60s Task: Periodic state reconciliation
                if now - last_recon_time >= 60:
                    if self.reconciler:
                        self.reconciler.reconcile_symbol(self.symbol)
                    last_recon_time = now

                # signal_interval Task: Signal generation tick
                if now - last_signal_time >= signal_interval_seconds:
                    self._signal_tick()

                    # Delta-neutral funding-arb tick
                    if self.funding_arb is not None:
                        try:
                            self.funding_arb.on_signal_tick()
                        except Exception as e:
                            logger.error("[ARB] funding-arb tick error: %s", e)

                    last_signal_time = now
                    iteration += 1
                    if max_iterations and iteration >= max_iterations:
                        break

                time.sleep(1)
        except KeyboardInterrupt:
            logger.info("Engine stopped by user")
        finally:
            self.stop()

    def _supervise_threads(self) -> bool:
        """G3: fail-stop if a background WS thread died silently.

        Returns True if it is safe to continue. On a dead feed/position-manager
        thread it trips HALT + the kill switch and halts the engine, rather than
        evaluating signals or managing positions against a stale feed.
        """
        if self.cfg is not None and not getattr(self.cfg, "thread_supervisor_enabled", True):
            return True
        dead = []
        if not self.ws_feed.is_alive():
            dead.append("ws_feed")
        if not self.ws_pm.is_alive():
            dead.append("ws_position_manager")
        if not dead:
            return True
        reason = f"WS thread(s) died: {', '.join(dead)}"
        logger.critical("[SUPERVISOR] %s — halting engine (fail-stop)", reason)
        try:
            from . import safe_mode
            safe_mode.trip_halt(reason)
        except Exception as e:
            logger.critical("[SUPERVISOR] Failed to trip HALT file: %s", e)
        if getattr(self, "risk_manager", None) is not None:
            self.risk_manager.trigger_kill_switch(reason)
        if self.event_bus:
            from .events import SystemFailureEvent
            self.event_bus.publish(SystemFailureEvent(component="thread_supervisor", error=reason))
        self._halted = True
        return False

    def _apply_runtime_overrides(self) -> None:
        """Poll the ConfigStore and apply runtime parameter overrides."""
        ov = self.config_store.poll()
        if ov is not None:
            # We got new overrides (could be empty dict if file deleted)
            for k, v in ov.items():
                cls = ConfigStore.classify(k)
                if cls == "safe":
                    # Apply immediately to cfg
                    if hasattr(self.cfg, k):
                        setattr(self.cfg, k, v)
                    # Apply to risk/adaptive/playbooks
                    if self.risk_manager is not None:
                        self.risk_manager.apply_overrides({k: v})
                    if self.adaptive_threshold is not None:
                        self.adaptive_threshold.apply_overrides({k: v})
                    if k.startswith("st2_") and self.playbook_st2 is not None:
                        self.playbook_st2.apply_overrides({k: v})
                    if k.startswith("mr_") and self.playbook_mr is not None:
                        self.playbook_mr.apply_overrides({k: v})
                elif cls == "flat_only":
                    self._pending_flat_overrides[k] = v
                elif cls == "restart":
                    logger.warning("[ConfigStore] Ignored restart-only parameter override: %s", k)
                else:
                    logger.warning("[ConfigStore] Ignored unknown/unblessed parameter override: %s", k)

        # Check if we are flat to drain flat-only overrides
        if not self._pending_flat_overrides:
            return

        position = self.wallet.get_open_position(self.symbol)
        if position is None:
            # Flat! Apply all deferred overrides
            logger.info("[ConfigStore] Symbol %s is flat — draining %d deferred flat-only overrides", self.symbol, len(self._pending_flat_overrides))
            for k, v in self._pending_flat_overrides.items():
                if hasattr(self.cfg, k):
                    setattr(self.cfg, k, v)
                if k.startswith("st2_") and self.playbook_st2 is not None:
                    self.playbook_st2.apply_overrides({k: v})
                if k.startswith("mr_") and self.playbook_mr is not None:
                    self.playbook_mr.apply_overrides({k: v})
            self._pending_flat_overrides = {}

    def _signal_tick(self):
        """Generate signals using REST data (runs every 5 min)."""
        if self._halted:
            logger.debug("[SIGNAL-TICK] %s is halted. Skipping.", self.symbol)
            return

        self._apply_runtime_overrides()

        logger.info("--- Signal Tick: %s ---", self.symbol)

        data = self._fetch_market_data()
        if data is None:
            return

        result = self._compute_regime_context(data)
        if result is None:
            return
        regime, regime_score, df_4h, rvol, adx_val, regime_ctx, session_ctx = result

        structure, structure_ltf = self._compute_market_structure(data)
        self._start_llm_async(data, regime, regime_score, regime_ctx, session_ctx, rvol)
        self._evaluate_and_enter(data, regime, regime_score, df_4h, rvol, adx_val, regime_ctx, session_ctx, structure, structure_ltf)
        self.wallet.print_summary()

    @staticmethod
    def _kline_limit(timeframe: str) -> int:
        """Return a sensible kline limit for a given timeframe string."""
        tf = timeframe.lower().strip()
        # Minutes: more bars needed for short TFs to build up ATR/indicators
        if tf.endswith("m"):
            try:
                mins = int(tf[:-1])
            except ValueError:
                return 200
            if mins <= 1:
                return 500
            if mins <= 5:
                return 400
            if mins <= 15:
                return 300
            return 200
        # Hours
        if tf.endswith("h"):
            try:
                h = int(tf[:-1])
            except ValueError:
                return 200
            return 200 if h <= 4 else 150
        # Daily / weekly / monthly
        return 200

    def _fetch_market_data(self):
        """Fetch all REST and WebSocket market data. Returns dict or None to skip tick."""
        try:
            # ── Fixed baseline TFs (used by regime, structure, LLM, legacy playbooks) ──
            df_4h = self.data_feed.get_klines(self.symbol, "4h", limit=200)
            df_1h = self.data_feed.get_klines(self.symbol, "1h", limit=150)
            df_15m = self.data_feed.get_klines(self.symbol, "15m", limit=150)
            df_5m = self.data_feed.get_klines(self.symbol, "5m", limit=150)

            # Get current context from WebSocket (real-time)
            ws_data = self.ws_feed.get_data()
            mark_price = ws_data.mark_price if ws_data.mark_price > 0 else self.data_feed.get_mark_price(self.symbol)

            funding_rate = self.data_feed.get_funding_rate(self.symbol)
            oi_data = self.data_feed.get_open_interest(self.symbol)
            taker_ratio = self.data_feed.get_taker_ratio(self.symbol)

            if mark_price <= 0:
                logger.warning(f"[WS-ENGINE] Invalid mark price {mark_price}. Skipping signal tick.")
                return None

        except StaleCandlesError as e:
            # A3: fallback klines too old — never generate a signal from stale
            # technicals. Skip the whole tick (already the behaviour; explicit
            # for clarity/observability).
            logger.warning(f"[WS-ENGINE] Stale klines — skipping signal tick: {e}")
            return None
        except Exception as e:
            logger.error(f"Data fetch failed — skipping signal tick: {e}")
            return None

        data = {
            "df_4h": df_4h, "df_1h": df_1h, "df_15m": df_15m, "df_5m": df_5m,
            "mark_price": mark_price, "funding_rate": funding_rate,
            "oi_data": oi_data, "taker_ratio": taker_ratio,
        }

        # ── ST2 configurable timeframes ──────────────────────────────────────
        # Resolve primary and HTF data for the Supertrend2 mode.  When the
        # configured TF matches a baseline already fetched above, reuse it
        # (no extra API call).  Otherwise fetch a fresh series.
        if self.playbook_st2 is not None:
            _baseline_map = {"1h": df_1h, "4h": df_4h, "15m": df_15m, "5m": df_5m}
            st2_tf = self.playbook_st2.timeframe
            st2_htf = self.playbook_st2.htf_timeframe

            if st2_tf in _baseline_map:
                data["df_st2"] = _baseline_map[st2_tf]
            else:
                try:
                    data["df_st2"] = self.data_feed.get_klines(
                        self.symbol, st2_tf, limit=self._kline_limit(st2_tf)
                    )
                    logger.debug("[ST2] Fetched primary TF %s (%d bars)", st2_tf, len(data["df_st2"]))
                except Exception as e:
                    logger.warning("[ST2] Failed to fetch primary TF %s: %s — falling back to 1h", st2_tf, e)
                    data["df_st2"] = df_1h

            if st2_htf in _baseline_map:
                data["df_st2_htf"] = _baseline_map[st2_htf]
            else:
                try:
                    data["df_st2_htf"] = self.data_feed.get_klines(
                        self.symbol, st2_htf, limit=self._kline_limit(st2_htf)
                    )
                    logger.debug("[ST2] Fetched HTF %s (%d bars)", st2_htf, len(data["df_st2_htf"]))
                except Exception as e:
                    logger.warning("[ST2] Failed to fetch HTF %s: %s — HTF filter will be skipped", st2_htf, e)
                    data["df_st2_htf"] = None

        # ── Mean Reversion configurable timeframe ────────────────────────────
        # Pre-fetch the MR kline series if the configured timeframe isn't one
        # of the baseline frames already fetched above, so _evaluate_entry_mr
        # and _mr_check_sma_exit never need to make a synchronous REST call
        # inside the signal-tick hot path.
        if self.playbook_mr is not None:
            _baseline_map_mr = {"15m": df_15m, "5m": df_5m, "1h": df_1h, "4h": df_4h}
            mr_tf = self.playbook_mr.timeframe
            if mr_tf in _baseline_map_mr:
                data["df_mr"] = _baseline_map_mr[mr_tf]
            else:
                try:
                    data["df_mr"] = self.data_feed.get_klines(
                        self.symbol, mr_tf,
                        limit=self.playbook_mr.sma_period + 10,
                    )
                    logger.debug("[MR] Fetched %s (%d bars)", mr_tf, len(data["df_mr"]))
                except Exception as e:
                    logger.warning("[MR] Failed to fetch %s klines: %s — will retry in tick", mr_tf, e)
                    data["df_mr"] = None

        return data

    def _compute_regime_context(self, data: dict):
        """Build session context, check kill zone gate, and compute extended regime.

        Returns (regime, regime_score, df_4h, rvol, adx_val, regime_ctx, session_ctx)
        or None if the tick should be skipped (kill zone gate).
        """
        df_4h = data["df_4h"]
        df_1h = data["df_1h"]

        # 1. Session context
        session_ctx = get_session_context()
        logger.info(
            f"[SESSION] {session_ctx.session.value} | "
            f"kill_zone={session_ctx.is_kill_zone} ({session_ctx.kill_zone_name or 'none'}) | "
            f"UTC={session_ctx.utc_hour:02d}h"
        )

        # Kill zone gate: if enabled, skip signal evaluation outside kill zones
        require_kz = getattr(self.cfg, "require_kill_zone", False) if self.cfg else False
        if require_kz and not session_ctx.is_kill_zone:
            logger.info("[SIGNAL-TICK] Outside kill zone — skipping (REQUIRE_KILL_ZONE=True)")
            return None

        # 2. Regime analysis
        regime, regime_score, df_4h = self.regime_analyzer.analyze(df_4h)

        # RVOL on the 1H frame (most relevant for intraday entries)
        rvol = calculate_rvol(df_1h, window=20)

        # OI delta: would require storing historical OI to compute a proper delta.
        # Using 0.0 for now — the raw oi value is still passed to the LLM prompt.
        oi_delta = 0.0

        # Liquidation intensity: normalise recent liquidation volume to 0–1
        liquidation_intensity = 0.0
        try:
            liq_df = self.data_feed.get_liquidation_orders(self.symbol)
            if liq_df is not None and not liq_df.empty and "quoteQty" in liq_df.columns:
                liq_vol = float(liq_df["quoteQty"].sum())
                # Normalise against a rough baseline of 1M USDT liquidations
                liquidation_intensity = min(liq_vol / 1_000_000, 1.0)
        except Exception as e:
            logger.debug("[SIGNAL-TICK] liquidation fetch skipped: %s", e)

        # Spread estimate for chaos detection (use WS spread if available)
        ws_spread_pct = 0.0
        try:
            _spread = self.ws_feed.get_spread()
            _mid = self.ws_feed.get_mid_price()
            if _mid > 0:
                ws_spread_pct = (_spread / _mid) * 100
        except Exception as e:
            logger.debug("[SIGNAL-TICK] spread fetch skipped: %s", e)

        # Extended regime classification
        adx_val = float(df_4h["adx"].iloc[-1]) if "adx" in df_4h.columns else 0.0
        regime_ctx: RegimeContext = self.regime_classifier.build_context(
            base_regime=regime,
            adx=adx_val,
            rvol=rvol,
            oi_delta=oi_delta,
            liquidation_intensity=liquidation_intensity,
            session_name=session_ctx.session.value,
            is_kill_zone=session_ctx.is_kill_zone,
            spread_pct=ws_spread_pct,
        )
        logger.info(
            f"[REGIME] {regime.value} (score={regime_score:.2f}) | "
            f"extended={regime_ctx.extended.value} | "
            f"rvol={rvol:.2f} | adx={adx_val:.1f} | size_x={regime_ctx.size_multiplier:.2f}"
        )

        return regime, regime_score, df_4h, rvol, adx_val, regime_ctx, session_ctx

    def _compute_market_structure(self, data: dict):
        """Run SMC market structure analysis on 1H and 15M frames.

        Returns (structure, structure_ltf). Returns (None, None) on exception.
        """
        df_1h = data["df_1h"]
        df_15m = data["df_15m"]

        # 3. Market structure analysis (SMC signals for playbook gating)
        structure = None
        structure_ltf = None
        try:
            msa = MarketStructureAnalyzer(df_1h, swing_window=3)
            structure = msa.analyze()
            recent_bos = structure.get("recent_bos")
            logger.debug(
                f"[STRUCTURE] BOS={recent_bos['type'] if recent_bos else 'None'} | "
                f"OBs={len(structure.get('unmitigated_order_blocks', []))} | "
                f"FVGs={len(structure.get('unmitigated_fvgs', []))}"
            )
            # Lower-timeframe structure for sweep+MSS confirmation (PlaybookSweepMSS).
            msa_ltf = MarketStructureAnalyzer(df_15m, swing_window=3)
            structure_ltf = msa_ltf.analyze()
        except Exception as e:
            logger.warning(f"[STRUCTURE] MarketStructureAnalyzer failed: {e}")
            structure = None
            structure_ltf = None

        return structure, structure_ltf

    def _start_llm_async(self, data: dict, regime, regime_score, regime_ctx, session_ctx, rvol):
        """Start the LLM advice thread asynchronously (step 4)."""
        if not (self.use_llm and self.advisor):
            return
        # Skip LLM when regime hard-blocks entries — saves GPU for useful calls.
        _dead_regimes = {"DEAD_MARKET", "HIGH_RISK_CHAOS", "LIQUIDATION_EVENT"}
        if regime_ctx is not None and regime_ctx.extended.value in _dead_regimes:
            logger.debug("[LLM] Skipping — regime=%s blocked", regime_ctx.extended.value)
            return
        # Skip if position already open — no entry evaluation will run.
        pos = self.wallet.get_open_position(self.symbol)
        if pos:
            logger.debug("[LLM] Skipping — position already open for %s", self.symbol)
            return
        if self._llm_thread is None or not self._llm_thread.is_alive():
            self._llm_thread = self.advisor.get_advice_async(
                symbol=self.symbol,
                df_5m=data["df_5m"],
                df_15m=data["df_15m"],
                df_1h=data["df_1h"],
                df_4h=data["df_4h"],
                regime=regime.value,
                regime_score=regime_score,
                mark_price=data["mark_price"],
                funding_rate=data["funding_rate"],
                oi_delta=0.0,
                taker_ratio=data["taker_ratio"],
                open_positions=[],
                market_regime=regime_ctx.extended.value,
                session=session_ctx.session.value,
                is_kill_zone=session_ctx.is_kill_zone,
                rvol=rvol,
            )

    # ── Supertrend2 helpers ───────────────────────────────────────────────────

    def _st2_check_flip_exit(self, data: dict, pos) -> bool:
        """
        Check whether the Supertrend2 direction has just flipped against the
        open position. If so, close it and return True.

        Called every signal tick (5 min) when strategy_mode == "supertrend2".
        The 1H Supertrend can flip at most once per hour so this granularity
        is more than sufficient.
        """
        if self.playbook_st2 is None:
            return False
        try:
            df_st2 = data.get("df_st2", data["df_1h"])
            if df_st2 is None or len(df_st2) < self.playbook_st2._min_bars():
                return False

            from .strategies.supertrend2 import compute_supertrend2
            atr_len = self.playbook_st2._effective_atr_len()
            _, direction = compute_supertrend2(df_st2, self.playbook_st2.factor, atr_len)

            curr_dir = int(direction.iloc[-1])
            prev_dir = int(direction.iloc[-2])

            if curr_dir == prev_dir:
                return False  # no flip this bar

            mark = data["mark_price"]
            from .wallet import PositionSide

            if pos.side == PositionSide.LONG and curr_dir == 1 and prev_dir == -1:
                self.wallet.close_position(self.symbol, float(mark), reason="ST2_FLIP_EXIT")
                logger.info(
                    "[ST2 EXIT] Long closed — Supertrend flipped to downtrend @ %.4f", mark
                )
                if self.event_bus:
                    from .events import SystemFailureEvent  # noqa: reuse log channel
                return True

            if pos.side == PositionSide.SHORT and curr_dir == -1 and prev_dir == 1:
                self.wallet.close_position(self.symbol, float(mark), reason="ST2_FLIP_EXIT")
                logger.info(
                    "[ST2 EXIT] Short closed — Supertrend flipped to uptrend @ %.4f", mark
                )
                return True

        except Exception as exc:
            logger.warning("[ST2 EXIT] flip-exit check failed: %s", exc)

        return False

    def _evaluate_entry_st2(
        self,
        data: dict,
        mark_price: float,
        funding_rate: float,
        taker_ratio: float,
        regime_ctx,
    ) -> None:
        """
        Entry evaluation path for strategy_mode == "supertrend2".

        Bypasses legacy playbooks, LLM fusion, and regime routing.
        Only the Supertrend2 flip/retracement signal and the funding-rate
        guard (safety net) control entry.  All risk-manager checks (daily
        limits, drawdown) and the execution path (_execute_entry) are reused.
        """
        if self.playbook_st2 is None:
            return

        df_st2 = data.get("df_st2", data["df_1h"])
        df_st2_htf = data.get("df_st2_htf", data["df_4h"]) if self.playbook_st2.use_htf_filter else None

        setup = self.playbook_st2.evaluate(df_st2, df_st2_htf)
        if not setup:
            logger.debug("[ST2 ENTRY] No signal this tick")
            return

        logger.info("[ST2 SIGNAL] %s | %s", setup["side"].value, setup["reason"])

        # Funding-rate extreme guard (keep for safety)
        _funding_extreme = self.cfg.funding_extreme_threshold if self.cfg else FUNDING_EXTREME
        if (
            (setup["side"].value in ("LONG", "BUY") and funding_rate > _funding_extreme)
            or (setup["side"].value in ("SHORT", "SELL") and funding_rate < -_funding_extreme)
        ):
            logger.info(
                "[ST2 BLOCKED] Funding extreme %+.4%% (threshold %.4%%)",
                funding_rate, _funding_extreme,
            )
            return

        dynamic_threshold = self.adaptive_threshold.get_threshold()

        self._execute_entry(EntryContext(
            setup=setup,
            final_score=1.0,          # ST2 signal is binary; always passes threshold
            llm_weight=0.0,
            explanation="Supertrend2 signal",
            mark_price=mark_price,
            funding_rate=funding_rate,
            oi_delta=0.0,
            taker_ratio=taker_ratio,
            tech_score=1.0,
            regime=None,
            regime_score=1.0,
            advice=None,
            dynamic_threshold=dynamic_threshold,
            regime_ctx=regime_ctx,
        ))

