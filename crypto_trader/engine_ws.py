DEFAULT_SYMBOL = "SOLUSDT"
LEVERAGE = 5
FUNDING_EXTREME = 0.0005


class WebSocketTradingEngine:
    """
    Hybrid engine: REST for signals, WebSocket for execution.

    Architecture:
        REST (5-min tick): Fetch 4H/1H → analyze regime → generate signal → LLM fusion
        WebSocket (1s): Monitor LTP → check SL/TP/Trail → execute entries/exits
    """

    def __init__(
        self,
        symbol: str = DEFAULT_SYMBOL,
        initial_balance: float = 1_000.0,
        leverage: int = LEVERAGE,
        use_llm: bool = True,
        llm_host: str = None,
        llm_model: str = None,
        log_responses: bool = False,
        log_rest: bool = False,
        log_ws: bool = False,
        log_llm: bool = False,
        wallet = None,
        event_bus = None,
        cfg = None,
        signal_publisher = None,
        risk_budget_fraction: float = 1.0,
        funding_arb = None,
    ):
        self.symbol = symbol.upper()
        self.use_llm = use_llm
        self.event_bus = event_bus
        self.cfg = cfg
        # Optional delta-neutral funding-arb manager (Strategy C). Runs alongside
        # the directional signal tick; None unless wired by the launcher.
        self.funding_arb = funding_arb
        # When set (live + Redis execution bus), entries are PUBLISHED as signals
        # and executed by the in-process consumer (shared wallet) — giving the
        # idempotency lock / DLQ / PEL-recovery / risk-gate safety on the live
        # entry path. When None, the hardened direct path runs unchanged.
        self.signal_publisher = signal_publisher
        # Fraction of the per-trade risk budget this engine may use. With a
        # SHARED wallet across N symbols (multi_engine), each engine sizes off
        # the full balance, so without this N symbols would each risk the full
        # 2% → up to 2N% concurrent. Set to 1/N to bound total exposure.
        self.risk_budget_fraction = max(0.0, min(1.0, float(risk_budget_fraction)))
        # CoinDCX market data for the cross-venue basis guard (F3). Public, no
        # creds; built lazily so paper/tests without network stay light.
        self._coindcx_md = None

        rest_logged = log_responses or log_rest
        ws_logged = log_responses or log_ws
        llm_logged = log_responses or log_llm

        # REST client (for historical data, funding, OI)
        self.data_feed = BinanceDataFeed(log_responses=rest_logged)

        # WebSocket client (for real-time LTP, mark price, bid/ask)
        self.ws_feed = BinanceWebSocketFeed(
            symbol=self.symbol,
            on_mark_price=self._on_mark_price,
            on_kline=self._on_kline,
            on_book_ticker=self._on_book_ticker,
            log_responses=ws_logged,
        )

        if wallet:
            self.wallet = wallet
        else:
            self.wallet = EnhancedFuturesWallet(
                symbol=self.symbol,
                initial_balance=initial_balance,
                leverage=leverage,
            )
        
        if cfg:
            self.risk_manager = RiskManager(
                max_daily_trades=cfg.max_daily_trades,
                max_orders_per_minute=cfg.max_orders_per_minute,
                max_margin_ratio=cfg.max_margin_ratio
            )
        else:
            self.risk_manager = RiskManager()
        self.adaptive_threshold = AdaptiveThresholdManager(
            base_threshold=FINAL_SCORE_THRESHOLD,
            min_threshold=0.50,
            decay_per_hour=0.01,
            target_trades_per_day=1.0
        )

        # Strategy
        self.regime_analyzer = MarketRegimeAnalyzer()
        self.playbook_a = PlaybookA()
        self.playbook_b = PlaybookB()
        self.playbook_ares = PlaybookAres()
        self.playbook_volx = PlaybookVolExhaust()
        self.playbook_sweep = PlaybookSweepMSS()

        # Regime / Session engine
        _rc_kwargs = {}
        if cfg:
            _rc_kwargs = dict(
                rvol_dead=cfg.rvol_dead_threshold,
                rvol_weak=cfg.rvol_weak_threshold,
                rvol_strong=cfg.rvol_strong_threshold,
                size_high=cfg.regime_size_multiplier_high,
                size_low=cfg.regime_size_multiplier_low,
            )
        self.regime_classifier = RegimeClassifier(**_rc_kwargs)

        # Journal
        self.journal = TradeJournal()

        # LLM
        self.advisor = None
        self._llm_thread = None
        if use_llm:
            use_cloud = os.getenv("USE_CLOUD_LLM", "false").lower() in ("true", "1", "yes")

            if use_cloud:
                resolved_host = os.getenv("CLOUD_OLLAMA_HOST", "https://ollama.com")
                resolved_model = os.getenv("CLOUD_OLLAMA_MODEL", "deepseek-v3:cloud")
                resolved_key = os.getenv("CLOUD_OLLAMA_API_KEY", "")
                logger.info(f"[LLM] Mode: CLOUD (Target: {resolved_host})")
            else:
                resolved_host = llm_host or os.getenv("OLLAMA_BASE_URL", os.getenv("OLLAMA_HOST", "http://localhost:11434"))
                resolved_model = llm_model or os.getenv("OLLAMA_MODEL", "qwen3.5:4b")
                resolved_key = os.getenv("OLLAMA_API_KEY", "")
                logger.info("[LLM] Mode: LOCAL")

            use_openai = os.getenv("USE_OPENAI_FORMAT", "false").lower() in ("true", "1", "yes")

            self.advisor = OllamaAdvisor(
                host=resolved_host,
                model=resolved_model,
                api_key=resolved_key,
                use_openai=use_openai,
                log_llm=llm_logged
            )
            if self.advisor.is_ready():
                logger.info(f"[LLM] Connected to {resolved_model}")
            else:
                logger.warning("[LLM] Ollama unavailable. Technical-only mode.")

        # WebSocket position manager (high-frequency exits)
        self.ws_pm = WebSocketPositionManager(
            ws_feed=self.ws_feed,
            wallet=self.wallet,
            check_interval_ms=1000,  # Check every 1 second
            event_bus=self.event_bus,
            # G4: drive the authoritative margin guard on the 1s loop (every ~5s),
            # not only on the 5-min signal tick — liquidation can't wait 5 min.
            health_check=self._check_authoritative_health,
            # A1: skip software exits on prices older than this.
            feed_stale_ms=(cfg.feed_stale_ms if cfg else 15000),
        )

        # State
        self._last_signal_candle_ms = 0
        self._pending_entry = None  # Signal waiting for WebSocket confirmation
        self._halted = False

        # Command Listeners
        if self.event_bus:
            from .events import CommandEvent, TradeClosedEvent
            self.event_bus.subscribe(CommandEvent, self._handle_command)
            self.event_bus.subscribe(TradeClosedEvent, self._on_trade_closed)

    def _on_trade_closed(self, event):
        """Update risk manager when a trade is closed."""
        if event.symbol == self.symbol:
            self.risk_manager.record_close(event.realized_pnl)

    def _handle_command(self, event):
        """Handle incoming commands from EventBus (e.g., Telegram)."""
        if event.command == "KILL_ALL" or (event.command == "KILL" and event.params.get("symbol") == self.symbol):
            self._halted = True
            logger.warning(f"🛑 [HALTED] {self.symbol} received KILL command.")
            # A remote KILL must flatten the live position, not just block new
            # entries — otherwise an open position rides on unattended.
            try:
                pos = self.wallet.get_open_position(self.symbol)
                if pos:
                    mark = self.ws_feed.get_ltp() or self.ws_feed.get_mid_price()
                    if not mark or mark <= 0:
                        mark = float(pos.entry_price)
                    self.wallet.close_position(self.symbol, float(mark), reason="REMOTE_KILL")
                    logger.warning(f"🛑 [KILL] flattened {self.symbol} on remote command")
            except Exception as e:
                logger.error("remote KILL flatten failed for %s: %s", self.symbol, e)
        
        elif event.command == "RESUME_ALL" or (event.command == "RESUME" and event.params.get("symbol") == self.symbol):
            self._halted = False
            logger.info(f"✅ [RESUMED] {self.symbol} received RESUME command.")

        elif event.command == "STATUS":
            # Engine will respond via logs or potentially publish a StatusEvent
            logger.info(f"📊 [STATUS] {self.symbol} | Halted: {self._halted} | Pos: {self.wallet.get_open_position(self.symbol) is not None}")

    # ── Lifecycle ──

    def start(self):
        """Start WebSocket and position manager."""
        logger.info(f"[ENGINE] Starting WebSocket engine for {self.symbol}")
        self.ws_feed.start()
        self.ws_pm.start()
        # Wait for WebSocket to connect
        for _ in range(10):
            if self.ws_feed.is_connected():
                break
            time.sleep(0.5)
        logger.info(f"[ENGINE] WebSocket connected: {self.ws_feed.is_connected()}")

    def stop(self):
        """Gracefully stop all components."""
        logger.info("[ENGINE] Stopping...")
        self.ws_pm.stop()
        self.ws_feed.stop()
        logger.info("[ENGINE] Stopped")

    def _check_authoritative_health(self):
        """Monitor authoritative exchange metrics (margin ratio) and trigger kill switch if unsafe."""
        if not self.cfg or not self.cfg.is_live:
            return

        from .exchanges.coindcx_execution import CoinDCXExecutionEngine
        if not isinstance(self.wallet.execution_engine, CoinDCXExecutionEngine):
            return

        try:
            details = self.wallet.execution_engine.get_cross_margin_details()
            if details:
                ratio = float(details.get("margin_ratio_cross", 0) or 0)
                ok, reason = self.risk_manager.check_margin_ratio(ratio)
                if not ok:
                    logger.critical(f"[AUTHORITATIVE GUARD] {reason}")
                    self.risk_manager.trigger_kill_switch(reason)
                    self._halted = True
                    if self.event_bus:
                        from .events import SystemFailureEvent
                        self.event_bus.publish(SystemFailureEvent(component="margin_guard", error=reason))
                    # Halting only blocks NEW entries; an open position is still
                    # racing toward liquidation at this margin ratio. Flatten it.
                    try:
                        pos = self.wallet.get_open_position(self.symbol)
                        if pos:
                            mark = self.ws_feed.get_ltp() or self.ws_feed.get_mid_price()
                            if not mark or mark <= 0:
                                mark = float(pos.entry_price)
                            self.wallet.close_position(
                                self.symbol, float(mark),
                                reason="MARGIN_GUARD_FLATTEN",
                            )
                            logger.critical("[AUTHORITATIVE GUARD] flattened %s to avoid liquidation", self.symbol)
                    except Exception as e:
                        logger.error("margin-guard flatten failed for %s: %s", self.symbol, e)
        except Exception as e:
            logger.error("Authoritative health check failed: %s", e)

    # ── Main Loop ──

    def run_loop(self, signal_interval_seconds: int = 300, max_iterations: int = None):
        """
        Main loop:
            - Every 5 min (default): REST fetch → signal generation → entry evaluation
            - Every 1 sec (WebSocket): Position monitoring → SL/TP/Trail execution
        """
        self.start()
        iteration = 0
        try:
            while True:
                # G3: supervise the WS threads — never trade on a dead/stale feed.
                if not self._supervise_threads():
                    break
                
                # Authoritative health check (margin ratio guard)
                self._check_authoritative_health()

                # Signal generation tick (REST-based)
                self._signal_tick()

                # Delta-neutral funding-arb tick (non-directional, orthogonal).
                if self.funding_arb is not None:
                    try:
                        self.funding_arb.on_signal_tick()
                    except Exception as e:
                        logger.error("[ARB] funding-arb tick error: %s", e)

                iteration += 1
                if max_iterations and iteration >= max_iterations:
                    break

                time.sleep(signal_interval_seconds)
        except KeyboardInterrupt:
            logger.info("Engine stopped by user")
        finally:
            self.stop()

    def _supervise_threads(self) -> bool:
        """G3: fail-stop if a background WS thread died silently.

        Returns True if it is safe to continue. On a dead feed/position-manager
        thread it trips HALT + the kill switch and halts the engine, rather than
        evaluating signals or managing positions against a stale feed.
        """
        if self.cfg is not None and not getattr(self.cfg, "thread_supervisor_enabled", True):
            return True
        dead = []
        if not self.ws_feed.is_alive():
            dead.append("ws_feed")
        if not self.ws_pm.is_alive():
            dead.append("ws_position_manager")
        if not dead:
            return True
        reason = f"WS thread(s) died: {', '.join(dead)}"
        logger.critical("[SUPERVISOR] %s — halting engine (fail-stop)", reason)
        try:
            from . import safe_mode
            safe_mode.trip_halt(reason)
        except Exception:
            pass
        if getattr(self, "risk_manager", None) is not None:
            self.risk_manager.trigger_kill_switch(reason)
        if self.event_bus:
            from .events import SystemFailureEvent
            self.event_bus.publish(SystemFailureEvent(component="thread_supervisor", error=reason))
        self._halted = True
        return False

    def _signal_tick(self):
        """Generate signals using REST data (runs every 5 min)."""
        if self._halted:
            logger.debug(f"[SIGNAL-TICK] {self.symbol} is halted. Skipping.")
            return

        logger.info(f"--- Signal Tick: {self.symbol} ---")

        try:
            # Fetch historical data via REST
            df_4h = self.data_feed.get_klines(self.symbol, "4h", limit=200)
            df_1h = self.data_feed.get_klines(self.symbol, "1h", limit=150)
            df_15m = self.data_feed.get_klines(self.symbol, "15m", limit=150)
            df_5m = self.data_feed.get_klines(self.symbol, "5m", limit=150)

            # Get current context from WebSocket (real-time)
            ws_data = self.ws_feed.get_data()
            mark_price = ws_data.mark_price if ws_data.mark_price > 0 else self.data_feed.get_mark_price(self.symbol)

            funding_rate = self.data_feed.get_funding_rate(self.symbol)
            oi_data = self.data_feed.get_open_interest(self.symbol)
            taker_ratio = self.data_feed.get_taker_ratio(self.symbol)

            if mark_price <= 0:
                logger.warning(f"[WS-ENGINE] Invalid mark price {mark_price}. Skipping signal tick.")
                return

        except StaleCandlesError as e:
            # A3: fallback klines too old — never generate a signal from stale
            # technicals. Skip the whole tick (already the behaviour; explicit
            # for clarity/observability).
            logger.warning(f"[WS-ENGINE] Stale klines — skipping signal tick: {e}")
            return
        except Exception as e:
            logger.error(f"Data fetch failed — skipping signal tick: {e}")
            return

        # 1. Session context
        session_ctx = get_session_context()
        logger.info(
            f"[SESSION] {session_ctx.session.value} | "
            f"kill_zone={session_ctx.is_kill_zone} ({session_ctx.kill_zone_name or 'none'}) | "
            f"UTC={session_ctx.utc_hour:02d}h"
        )

        # Kill zone gate: if enabled, skip signal evaluation outside kill zones
        require_kz = getattr(self.cfg, "require_kill_zone", False) if self.cfg else False
        if require_kz and not session_ctx.is_kill_zone:
            logger.info("[SIGNAL-TICK] Outside kill zone — skipping (REQUIRE_KILL_ZONE=True)")
            return

        # 2. Regime analysis
        regime, regime_score, df_4h = self.regime_analyzer.analyze(df_4h)

        # RVOL on the 1H frame (most relevant for intraday entries)
        rvol = calculate_rvol(df_1h, window=20)

        # OI delta: would require storing historical OI to compute a proper delta.
        # Using 0.0 for now — the raw oi value is still passed to the LLM prompt.
        oi_delta = 0.0

        # Liquidation intensity: normalise recent liquidation volume to 0–1
        liquidation_intensity = 0.0
        try:
            liq_df = self.data_feed.get_liquidation_orders(self.symbol)
            if liq_df is not None and not liq_df.empty and "quoteQty" in liq_df.columns:
                liq_vol = float(liq_df["quoteQty"].sum())
                # Normalise against a rough baseline of 1M USDT liquidations
                liquidation_intensity = min(liq_vol / 1_000_000, 1.0)
        except Exception:
            pass

        # Spread estimate for chaos detection (use WS spread if available)
        ws_spread_pct = 0.0
        try:
            _spread = self.ws_feed.get_spread()
            _mid = self.ws_feed.get_mid_price()
            if _mid > 0:
                ws_spread_pct = (_spread / _mid) * 100
        except Exception:
            pass

        # Extended regime classification
        adx_val = float(df_4h["adx"].iloc[-1]) if "adx" in df_4h.columns else 0.0
        regime_ctx: RegimeContext = self.regime_classifier.build_context(
            base_regime=regime,
            adx=adx_val,
            rvol=rvol,
            oi_delta=oi_delta,
            liquidation_intensity=liquidation_intensity,
            session_name=session_ctx.session.value,
            is_kill_zone=session_ctx.is_kill_zone,
            spread_pct=ws_spread_pct,
        )
        logger.info(
            f"[REGIME] {regime.value} (score={regime_score:.2f}) | "
            f"extended={regime_ctx.extended.value} | "
            f"rvol={rvol:.2f} | adx={adx_val:.1f} | size_x={regime_ctx.size_multiplier:.2f}"
        )

        # 3. Market structure analysis (SMC signals for playbook gating)
        structure = None
        structure_ltf = None
        try:
            msa = MarketStructureAnalyzer(df_1h, swing_window=3)
            structure = msa.analyze()
            recent_bos = structure.get("recent_bos")
            logger.debug(
                f"[STRUCTURE] BOS={recent_bos['type'] if recent_bos else 'None'} | "
                f"OBs={len(structure.get('unmitigated_order_blocks', []))} | "
                f"FVGs={len(structure.get('unmitigated_fvgs', []))}"
            )
            # Lower-timeframe structure for sweep+MSS confirmation (PlaybookSweepMSS).
            msa_ltf = MarketStructureAnalyzer(df_15m, swing_window=3)
            structure_ltf = msa_ltf.analyze()
        except Exception as e:
            logger.warning(f"[STRUCTURE] MarketStructureAnalyzer failed: {e}")
            structure = None
            structure_ltf = None

        # 4. Start LLM async (pass extended regime for richer context)
        if self.use_llm and self.advisor:
            pos = self.wallet.get_open_position(self.symbol)
            open_positions = [pos.to_dict()] if pos else []
            if self._llm_thread is None or not self._llm_thread.is_alive():
                self._llm_thread = self.advisor.get_advice_async(
                    symbol=self.symbol,
                    df_5m=df_5m,
                    df_15m=df_15m,
                    df_1h=df_1h,
                    df_4h=df_4h,
                    regime=regime.value,
                    regime_score=regime_score,
                    mark_price=mark_price,
                    funding_rate=funding_rate,
                    oi_delta=oi_delta,
                    taker_ratio=taker_ratio,
                    open_positions=open_positions,
                    market_regime=regime_ctx.extended.value,
                    session=session_ctx.session.value,
                    is_kill_zone=session_ctx.is_kill_zone,
                    rvol=rvol,
                )

        # 5. Risk check
        self.risk_manager.update_peak_balance(self.wallet.margin_balance)
        # Assuming initial balance for daily drawdown is the wallet balance minus daily PnL
        initial_daily_balance = float(self.wallet.wallet_balance) - self.risk_manager.daily_pnl
        can_trade, risk_reason = self.risk_manager.can_trade(
            current_balance=self.wallet.margin_balance,
            initial_daily_balance=initial_daily_balance
        )
        if not can_trade:
            if not getattr(self, "_halt_published", False):
                if self.event_bus:
                    from .events import RiskHaltEvent
                    self.event_bus.publish(RiskHaltEvent(
                        reason=risk_reason,
                        daily_pnl=float(self.wallet.realized_pnl_total),
                        trades_today=self.risk_manager.daily_count
                    ))
                self._halt_published = True
            logger.info(f"[RISK] {risk_reason}")
            return
        self._halt_published = False

        # 5.5 Update position if open (to check AI and regime reversal exits)
        pos = self.wallet.get_open_position(self.symbol)
        if pos:
            df_1h["ema9"] = compute_ema(df_1h["close"], 9)
            ema9_val = df_1h["ema9"].iloc[-1]
            ema9_1h = float(ema9_val) if pd.notna(ema9_val) else None
            candle_close_time = int(df_1h["close_time"].iloc[-1].timestamp() * 1000)

            advice = self.advisor.get_last_advice() if (self.use_llm and self.advisor) else None
            current_llm_advice = advice.to_dict() if advice else None

            self.wallet.update_positions(
                self.symbol,
                mark_price,
                candle_close_time,
                ema9_1h,
                current_llm_advice=current_llm_advice,
                current_regime=regime.value if regime else None,
            )

        # 6. Evaluate entry if no open position
        if not self.wallet.get_open_position(self.symbol) and can_trade:
            # Block entry when regime forbids it (DEAD_MARKET, HIGH_RISK_CHAOS, LIQUIDATION_EVENT)
            if not regime_ctx.allows_new_entries():
                logger.info(
                    f"[REGIME-BLOCK] No entry — extended regime is {regime_ctx.extended.value}"
                )
                return

            # Get latest ADX for Ares playbook filter
            latest_adx = df_4h["adx"].iloc[-1] if "adx" in df_4h.columns else None
            try:
                self._evaluate_entry(df_1h, df_4h, df_15m, regime, regime_score, mark_price,
                                    funding_rate, oi_delta, taker_ratio, structure=structure,
                                    adx_1h=latest_adx, regime_ctx=regime_ctx,
                                    session_ctx=session_ctx, structure_ltf=structure_ltf)
            except Exception as e:
                # An exception mid-entry (e.g. order placed but booking/SL failed)
                # could leave an unmanaged live position. Fail safe: HALT, trip
                # the kill switch, and reconcile against the venue rather than
                # letting the loop crash and abandon a naked position.
                logger.critical("[ENTRY FAILURE] %s — halting and reconciling: %s", self.symbol, e)
                self._halted = True
                if getattr(self, "risk_manager", None) is not None:
                    self.risk_manager.trigger_kill_switch(f"entry failure: {e}")
                if self.cfg and self.cfg.is_live:
                    try:
                        from . import safe_mode
                        safe_mode.trip_halt(f"entry failure for {self.symbol}: {e}")
                    except Exception:
                        pass
                if self.event_bus:
                    from .events import SystemFailureEvent
                    self.event_bus.publish(SystemFailureEvent(component="entry", error=str(e)))

        # 6. Print summary
        self.wallet.print_summary()

    # Regime → allowed strategy order. Empty list means no entries.
    _REGIME_STRATEGY_MAP: dict = {
        ExtendedRegime.TREND_EXPANSION:      ["playbook_a", "playbook_b"],
        ExtendedRegime.BREAKOUT_ENVIRONMENT: ["playbook_b", "playbook_a", "playbook_sweep"],
        ExtendedRegime.ACCUMULATION:         ["playbook_a", "playbook_sweep"],
        ExtendedRegime.MEAN_REVERSION:       ["playbook_ares", "playbook_volx", "playbook_sweep"],
        ExtendedRegime.LOW_VOL_CHOP:         ["playbook_ares", "playbook_volx"],
        ExtendedRegime.LIQUIDATION_EVENT:    [],
        ExtendedRegime.DEAD_MARKET:          [],
        ExtendedRegime.HIGH_RISK_CHAOS:      [],
    }

    @staticmethod
    def _bias_factor(side, advice) -> float:
        """Selection-only tiebreak: down-weight a candidate whose side contradicts
        the LLM's recommended bias. Returns a multiplier in [0,1]. Never used for
        the threshold gate (that uses the true fused score) — only for ranking."""
        if advice is None:
            return 1.0
        rec = getattr(advice, "recommended_bias", "any")
        if rec == "none":
            return 0.5  # LLM wants no trades — push all candidates down
        if rec == "long_only" and side == PositionSide.SHORT:
            return 0.6
        if rec == "short_only" and side == PositionSide.LONG:
            return 0.6
        return 1.0

    def _evaluate_entry(self, df_1h, df_4h, df_15m, regime, regime_score, mark_price,
                        funding_rate, oi_delta, taker_ratio, structure=None, adx_1h=None,
                        regime_ctx: Optional[RegimeContext] = None,
                        session_ctx=None, structure_ltf=None):
        """Evaluate entry signals and execute via WebSocket LTP.

        Score-based best-of: every playbook allowed for the current regime is
        evaluated; each candidate is LLM-fused, and the highest-scoring one
        (bias-aware ranking) that clears the dynamic threshold is executed.
        """
        # Determine allowed playbooks from extended regime (fallback: legacy order)
        if regime_ctx is not None:
            allowed = self._REGIME_STRATEGY_MAP.get(
                regime_ctx.extended,
                ["playbook_ares", "playbook_a", "playbook_b"],
            )
        else:
            allowed = ["playbook_ares", "playbook_a", "playbook_b"]

        if not allowed:
            logger.info(f"[ROUTER] No strategies allowed for {regime_ctx.extended.value if regime_ctx else 'unknown'}")
            return

        logger.info(f"[ROUTER] allowed_strategies={allowed}")

        playbook_map = {
            "playbook_ares":  lambda: self.playbook_ares.evaluate(df_15m, adx_1h=adx_1h),
            "playbook_volx":  lambda: self.playbook_volx.evaluate(df_15m, adx_1h=adx_1h),
            "playbook_a":     lambda: self.playbook_a.evaluate(df_1h, regime, structure=structure),
            "playbook_b":     lambda: self.playbook_b.evaluate(df_1h, df_4h, regime, structure=structure),
            "playbook_sweep": lambda: self.playbook_sweep.evaluate(
                df_1h, df_15m, structure, structure_ltf, regime=regime),
        }
        playbook_labels = {
            "playbook_ares":  "PLAYBOOK ARES",
            "playbook_volx":  "PLAYBOOK VOLX",
            "playbook_a":     "PLAYBOOK A",
            "playbook_b":     "PLAYBOOK B",
            "playbook_sweep": "PLAYBOOK SWEEP",
        }

        advice = self.advisor.get_last_advice() if self.advisor else None
        dynamic_threshold = self.adaptive_threshold.get_threshold()

        # Evaluate ALL allowed playbooks and fuse each, then pick the best.
        candidates = []  # (rank_score, final_score, llm_weight, explanation, pb_key, setup)
        for pb_key in allowed:
            evaluator = playbook_map.get(pb_key)
            if evaluator is None:
                continue
            try:
                setup = evaluator()
            except Exception as e:
                logger.warning(f"[{playbook_labels.get(pb_key, pb_key)}] evaluate failed: {e}")
                continue
            if not setup:
                continue

            tech_score = setup["score"]
            if self.advisor and advice:
                final_score, llm_weight, explanation = self.advisor.compute_final_score(
                    technical_score=tech_score,
                    regime=regime.value,
                    regime_score=regime_score,
                    advice=advice,
                )
            else:
                final_score, llm_weight, explanation = tech_score, 0.0, "LLM unavailable"

            rank_score = final_score * self._bias_factor(setup["side"], advice)
            logger.info(
                f"[{playbook_labels[pb_key]}] candidate: {setup['side'].value} | "
                f"tech={tech_score:.2f} | final={final_score:.2f} | rank={rank_score:.2f}"
            )
            candidates.append((rank_score, final_score, llm_weight, explanation, pb_key, setup))

        if not candidates:
            return

        # Best-of: highest bias-aware rank score wins.
        candidates.sort(key=lambda c: c[0], reverse=True)
        rank_score, final_score, llm_weight, explanation, pb_key, setup = candidates[0]
        logger.info(
            f"[SELECT] winner={playbook_labels[pb_key]} | {setup['side'].value} | "
            f"final={final_score:.2f} | {len(candidates)} candidate(s)"
        )

        # Correlation check
        active_positions = {s: p.to_dict() for s, p in self.wallet.positions.items() if p.status == "OPEN"}
        ok, corr_reason = self.risk_manager.check_correlation(self.symbol, setup["side"].value, active_positions)
        if not ok:
            logger.info(f"[BLOCKED] {corr_reason}")
            return

        if self.advisor and advice:
            logger.info(f"[FUSION] {explanation} | final={final_score:.2f}")

        if final_score < dynamic_threshold:
            logger.info(f"[BLOCKED] Final score {final_score:.2f} < {dynamic_threshold:.2f}")
            return
        if (
            (setup["side"] == PositionSide.LONG and funding_rate > FUNDING_EXTREME)
            or (setup["side"] == PositionSide.SHORT and funding_rate < -FUNDING_EXTREME)
        ):
            logger.info(
                f"[BLOCKED] Funding extreme for {setup['side'].value}: {funding_rate:+.4%} "
                f"(threshold={FUNDING_EXTREME:.2%})"
            )
            return

        # Execute entry using WebSocket LTP for precise price
        self._execute_entry(setup, final_score, llm_weight, explanation,
                           mark_price, funding_rate, oi_delta, taker_ratio,
                           setup["score"], regime, regime_score, advice, dynamic_threshold,
                           regime_ctx=regime_ctx)

    def _coindcx_market_data(self):
        if self._coindcx_md is None:
            from .exchanges.coindcx_market_data import CoinDCXMarketData
            self._coindcx_md = CoinDCXMarketData()
        return self._coindcx_md

    def _basis_guard(self, side, binance_mark: float):
        """Cross-venue basis guard (F3).

        Signals fire on Binance price but fills happen on CoinDCX. Reject the
        entry when the venues diverge beyond the configured threshold. Returns
        ``(allowed, basis)``. If CoinDCX data is unavailable, skip the guard
        (don't block trading on a missing fallback feed).
        """
        cfg = self.cfg
        if cfg is None or not getattr(cfg, "basis_guard_enabled", False) or binance_mark <= 0:
            return True, 0.0
        try:
            cdcx_mark = self._coindcx_market_data().get_mark_price(self.symbol)
        except Exception as e:
            logger.warning("[BASIS] CoinDCX mark unavailable (%s); skipping guard", e)
            return True, 0.0
        if cdcx_mark <= 0:
            return True, 0.0
        basis = (cdcx_mark - binance_mark) / binance_mark
        if abs(basis) > cfg.max_cross_venue_basis:
            logger.warning(
                f"[BASIS BLOCKED] {self.symbol} basis {basis:+.4%} exceeds "
                f"{cfg.max_cross_venue_basis:.2%} (binance={binance_mark:.4f} coindcx={cdcx_mark:.4f})"
            )
            if self.event_bus:
                from .events import SignalRejectedEvent
                self.event_bus.publish(SignalRejectedEvent(
                    symbol=self.symbol,
                    reason=f"cross-venue basis {basis:+.4%} > {cfg.max_cross_venue_basis:.2%}",
                ))
            return False, basis
        return True, basis

    def _execute_entry(self, setup, final_score, llm_weight, explanation,
                      mark_price, funding_rate, oi_delta, taker_ratio,
                      tech_score, regime, regime_score, advice, dynamic_threshold,
                      regime_ctx: Optional[RegimeContext] = None):
        """Execute entry using real-time WebSocket prices."""
        # A1: never enter on stale data. If the WS feed has no fresh price within
        # the staleness budget, veto the entry rather than fall back to a possibly
        # seconds-old price. (Exits are separately gated in ws_pm.)
        stale_ms = self.cfg.feed_stale_ms if self.cfg else 15000
        if not self.ws_feed.is_fresh(stale_ms):
            age = self.ws_feed.data_age_ms()
            logger.warning("[ENTRY] WS feed stale (age=%sms > %dms) — vetoing entry", age, stale_ms)
            return

        # Get current LTP and spread from WebSocket
        ltp = self.ws_feed.get_ltp()
        mid = self.ws_feed.get_mid_price()
        spread = self.ws_feed.get_spread()

        if ltp <= 0 or mid <= 0:
            logger.warning("[ENTRY] WebSocket LTP/mid unavailable (ltp=%.4f mid=%.4f) — vetoing entry", ltp, mid)
            return

        # Slippage estimate: if spread > 0.1%, log warning
        spread_pct = spread / mid * 100 if mid > 0 else 0
        if spread_pct > 0.1:
            logger.warning(f"[ENTRY] Wide spread: {spread_pct:.3f}% | bid={self.ws_feed.data.best_bid:.2f} ask={self.ws_feed.data.best_ask:.2f}")

        # F3: cross-venue basis guard — reject if Binance and CoinDCX diverge.
        allowed, _basis = self._basis_guard(setup["side"], mid if mid > 0 else mark_price)
        if not allowed:
            return

        # Adjust entry price to use mid price (fairer than LTP which can be stale).
        # F3: nudge the trigger toward the fill venue by the basis buffer so risk
        # sizing reflects the price we'll actually fill on at CoinDCX.
        entry_price = mid
        buf = self.cfg.entry_basis_buffer if (self.cfg and getattr(self.cfg, "basis_guard_enabled", False)) else 0.0
        if buf:
            entry_price = mid * (1 + buf) if setup["side"] == PositionSide.LONG else mid * (1 - buf)

        # Re-anchor the PLAYBOOK's stop/target to the actual fill entry.
        # The playbook computed sl/tp off its signal price; the real entry (mid +
        # basis buffer) differs slightly, so we preserve the playbook's
        # proportional stop distance rather than discarding it for a flat default.
        is_long = setup["side"] == PositionSide.LONG
        pb_entry = float(setup.get("entry_price") or 0)
        default_sl_pct, default_tp_pct = 0.007, 0.010

        def _reanchor(level_price, fallback_pct, is_stop):
            """Map a playbook level to the actual entry, keeping its ratio."""
            if pb_entry > 0 and level_price and float(level_price) > 0:
                return entry_price * (float(level_price) / pb_entry)
            # No usable playbook level — fall back to a flat default.
            if is_stop:
                return entry_price * (1 - fallback_pct) if is_long else entry_price * (1 + fallback_pct)
            return entry_price * (1 + fallback_pct) if is_long else entry_price * (1 - fallback_pct)

        sl = _reanchor(setup.get("sl_price"), default_sl_pct, is_stop=True)

        # Update setup with actual entry price + re-anchored stop.
        setup["entry_price"] = entry_price
        setup["sl_price"] = sl
        if "tp_price" in setup:
            setup["tp_price"] = _reanchor(setup.get("tp_price"), default_tp_pct, is_stop=False)
        else:
            for tp_level in setup.get("tp_levels", []):
                lvl_default = 0.010 if tp_level.get("label") == "TP1" else 0.020
                tp_level["price"] = _reanchor(tp_level.get("price"), lvl_default, is_stop=False)

        # Representative TP for events/logging (first target, or single tp_price).
        tp = setup.get("tp_price")
        if tp is None:
            _levels = setup.get("tp_levels", [])
            tp = _levels[0]["price"] if _levels else entry_price

        # Risk-based sizing from stop distance (2% risk per trade, scaled by this
        # engine's share of a shared wallet to avoid multi-symbol over-allocation).
        stop_distance = abs(entry_price - setup["sl_price"])
        risk_budget = self.wallet.margin_balance * Decimal("0.02") * Decimal(str(self.risk_budget_fraction))
        size_multiplier = min(final_score / dynamic_threshold, 1.0)
        # Apply regime-based size scalar (e.g. 1.25× for TREND_EXPANSION, 0.5× for LOW_VOL_CHOP)
        if regime_ctx is not None and regime_ctx.size_multiplier != 1.0:
            size_multiplier *= regime_ctx.size_multiplier
            logger.debug(
                f"[SIZING] regime={regime_ctx.extended.value} size_x={regime_ctx.size_multiplier:.2f} "
                f"→ combined_multiplier={size_multiplier:.3f}"
            )
        risk_budget *= Decimal(str(size_multiplier))
        stop_distance_dec = Decimal(str(stop_distance))
        quantity = (risk_budget / stop_distance_dec) if stop_distance_dec > 0 else Decimal("0")

        trade_id = str(uuid.uuid4())[:8]

        if quantity <= 0:
            logger.warning("[ENTRY] computed quantity <= 0 (stop_distance=%s); skipping", stop_distance)
            return

        # Entry order style: maker-limit only when globally enabled AND the
        # winning playbook requested it (volx/sweep); otherwise market (default).
        cfg_style = getattr(self.cfg, "entry_order_style", "market") if self.cfg else "market"
        use_maker = (
            str(cfg_style).lower() == "maker_limit"
            and str(setup.get("entry_order_style", "market")).lower() == "maker_limit"
        )
        setup["entry_order_style"] = "maker_limit" if use_maker else "market"

        # Decoupled path: publish the entry as a signal. The in-process consumer
        # (shared wallet) executes it with idempotency/DLQ/PEL-recovery + a final
        # risk-gate veto, then emits TradeOpenedEvent. record_open is performed
        # exactly once by the consumer's risk gate, so we do NOT record it here.
        if self.signal_publisher is not None:
            from .execution.signal_bus import Signal
            meta = {
                "sl_price": float(setup["sl_price"]),
                "regime": regime.value if regime else "",
                "extended_regime": regime_ctx.extended.value if regime_ctx else "",
                "tech_score": float(tech_score),
                "llm_decision": "ALLOW" if final_score >= dynamic_threshold else "LLM_VETOED",
                "funding_rate": float(funding_rate),
                "oi_delta": float(oi_delta),
                "rvol": float(regime_ctx.rvol) if regime_ctx else 1.0,
                "entry_order_style": setup["entry_order_style"],
            }
            if use_maker and self.cfg:
                meta["maker_limit_timeout_s"] = float(self.cfg.maker_limit_timeout_s)
                meta["maker_limit_offset_bps"] = float(self.cfg.maker_limit_offset_bps)
                meta["maker_limit_fallback"] = str(self.cfg.maker_limit_fallback)
            if "time_stop_hours" in setup:
                meta["time_stop_hours"] = setup["time_stop_hours"]
            if "tp_price" in setup:
                meta["tp_price"] = float(setup["tp_price"])
            else:
                meta["tp_levels"] = [
                    {"price": float(t["price"]), "pct": float(t.get("pct", 1.0)),
                     "label": t.get("label", "TP")}
                    for t in setup.get("tp_levels", []) if t.get("price")
                ]
            mode = self.cfg.mode.value if self.cfg else "paper"
            self.signal_publisher.emit(Signal(
                strategy_id=f"engine_ws:{self.symbol}",
                symbol=self.symbol, side=setup["side"].value,
                quantity=float(quantity), mode=mode,
                order_type="limit" if use_maker else "market",
                price=float(entry_price), metadata=meta,
            ))
            self.adaptive_threshold.record_trade()
            logger.info("[EXECUTED→BUS] %s %s qty=%.4f @ %.4f style=%s published to execution bus",
                        self.symbol, setup["side"].value, float(quantity), float(entry_price),
                        setup["entry_order_style"])
            return

        # Direct path. For live maker-limit, acquire the passive fill lock-free
        # (never under the shared wallet lock), then book it; on a skip-fallback
        # miss, abort the entry. Paper maker-limit is simulated in open_position
        # via the setup flag. Market entries are unchanged.
        external_fill = None
        book_qty = quantity
        if use_maker and self.cfg and self.cfg.is_live:
            external_fill = self.wallet.acquire_live_entry_fill(
                self.symbol, setup["side"], quantity, Decimal(str(entry_price)),
                timeout_s=self.cfg.maker_limit_timeout_s,
                offset_bps=self.cfg.maker_limit_offset_bps,
                fallback=self.cfg.maker_limit_fallback,
            )
            if external_fill is None:
                logger.info("[MAKER-LIMIT] %s entry skipped (unfilled, fallback=skip)", self.symbol)
                return
            fq = external_fill.get("filled_quantity")
            if fq is not None:
                book_qty = Decimal(str(fq))

        pos = self.wallet.open_position(
            self.symbol,
            setup,
            entry_price,
            custom_margin=None,
            custom_quantity=book_qty,
            external_fill=external_fill,
        )

        if pos:
            self.risk_manager.record_open()
            self.adaptive_threshold.record_trade()

            # Calculate slippage
            intended = setup["entry_price"]
            actual = entry_price
            slippage = abs(actual - intended) / intended * 100 if intended > 0 else 0

            self.journal.log_open(
                trade_id=trade_id,
                symbol=self.symbol,
                regime=regime.value,
                regime_score=regime_score,
                setup=setup,
                technical_score=tech_score,
                llm_advice=advice.to_dict() if self.advisor and advice else None,
                llm_weight=llm_weight,
                final_score=final_score,
                margin=pos.margin_used,
                notional=pos.notional,
                entry_price=entry_price,
                funding_rate=funding_rate,
                oi_delta=oi_delta,
                taker_ratio=taker_ratio,
            )

            logger.info(
                f"[EXECUTED] Trade {trade_id} | Entry={entry_price:.2f} | "
                f"Margin={pos.margin_used:.2f} | Score={final_score:.2f} | "
                f"Spread={spread_pct:.3f}% | Slippage={slippage:.3f}%"
            )

            # Publish Event for Telegram
            if self.event_bus:
                from .events import TradeOpenedEvent
                self.event_bus.publish(TradeOpenedEvent(
                    symbol=self.symbol,
                    side=setup["side"].value,
                    leverage=self.wallet.leverage,
                    entry_price=entry_price,
                    stop_loss=sl,
                    take_profit=tp,
                    margin=pos.margin_used,
                    notional=pos.notional,
                    regime=regime.value,
                    tech_score=tech_score,
                    llm_decision="ALLOW" if final_score >= dynamic_threshold else "LLM_VETOED",
                    funding=funding_rate,
                    oi_delta=oi_delta,
                    liquidation_price=float(self.wallet.liquidation_price(pos)),
                ))

