LLM_VETO_THRESHOLD = -0.70  # Below this, LLM vetoes the technical signal entirely

# ---------------------------------------------------------------------------
# LLM Response Schema
# ---------------------------------------------------------------------------

class LLMBias(Enum):
    BULLISH = "bullish"
    BEARISH = "bearish"
    NEUTRAL = "neutral"
    UNCLEAR = "unclear"

class LLMRiskLevel(Enum):
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    EXTREME = "extreme"

@dataclass
class LLMAdvice:
    timestamp: int
    symbol: str
    bias: LLMBias
    confidence: float           # 0.0 – 1.0
    sentiment_score: float      # -1.0 (bearish) to +1.0 (bullish)
    risk_level: LLMRiskLevel
    key_factors: List[str]
    recommended_bias: Literal["long_only", "short_only", "any", "none"]
    technical_alignment: float  # How much LLM agrees with current technical regime
    veto: bool = False          # True if LLM says "do not trade"
    veto_reason: Optional[str] = None  # Explanation when veto=True; None means no veto
    raw_response: str = ""

    def to_dict(self) -> dict:
        return {
            "timestamp": self.timestamp,
            "symbol": self.symbol,
            "bias": self.bias.value,
            "confidence": round(self.confidence, 3),
            "sentiment_score": round(self.sentiment_score, 3),
            "risk_level": self.risk_level.value,
            "key_factors": self.key_factors,
            "recommended_bias": self.recommended_bias,
            "technical_alignment": round(self.technical_alignment, 3),
            "veto": self.veto,
            "veto_reason": self.veto_reason,
        }


