"""
Ollama LLM Integration for SOL 10× Snap Trading System
========================================================
Provides an AI advisor layer that:
    • Analyzes market structure, sentiment, and risk factors
    • Returns structured JSON bias signals (NOT direct trade orders)
    • Caches responses to avoid redundant LLM calls
    • Operates asynchronously so it never blocks the trading loop
    • Acts as a FILTER and MODIFIER, never as a primary signal generator

Architecture Principle:
    Technical indicators (EMA, RSI, volume) generate the signal.
    LLM provides a CONFIDENCE MODIFIER (-1.0 to +1.0) and RISK FLAG.
    If LLM strongly disagrees with the technical signal, the trade is blocked.

Author: Generated by Kimi K2.6
"""

