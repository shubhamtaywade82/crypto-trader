class OllamaAdvisor:
    """
    High-level advisor that integrates LLM intelligence into the trading loop.
    Usage:
        advisor = OllamaAdvisor()
        advice = advisor.get_advice(symbol, df_1h, df_4h, regime, mark_price, positions)
        if advice and advice.veto:
            logger.info(f"LLM vetoed trade: {advice.veto_reason}")
    """

    def __init__(
        self,
        host: str = OLLAMA_HOST,
        model: str = OLLAMA_MODEL,
        timeout: int = OLLAMA_TIMEOUT,
        cache_ttl: int = CACHE_TTL_SECONDS,
        min_confidence: float = LLM_MIN_CONFIDENCE,
        veto_threshold: float = LLM_VETO_THRESHOLD,
    ):
        self.client = OllamaClient(host=host, model=model, timeout=timeout)
        self.parser = LLMResponseParser()
        self.cache = LLMCache(ttl=cache_ttl, model=model)  # model in key → no cross-model cache hits
        self.min_confidence = min_confidence
        self.veto_threshold = veto_threshold
        self._last_advice: Optional[LLMAdvice] = None
        self._advice_lock = threading.Lock()

    def is_ready(self) -> bool:
        return self.client.is_available()

    def get_advice(
        self,
        symbol: str,
        df_1h: pd.DataFrame,
        df_4h: pd.DataFrame,
        regime: str,
        mark_price: float,
        open_positions: List[dict],
        force_refresh: bool = False,
    ) -> Optional[LLMAdvice]:
        """
        Get LLM advice. Returns None if LLM is unavailable, cache miss, or parse failure.
        This is a SYNCHRONOUS call (blocking). For non-blocking, use get_advice_async().
        """
        prompt = build_market_prompt(symbol, df_1h, df_4h, regime, mark_price, open_positions)

        # Check cache
        if not force_refresh:
            cached = self.cache.get(symbol, prompt)
            if cached:
                logger.debug("LLM cache hit")
                with self._advice_lock:
                    self._last_advice = cached
                return cached

        # Call LLM
        raw = self.client.generate(prompt)
        if not raw:
            logger.warning("LLM returned no response; using last advice if available")
            with self._advice_lock:
                return self._last_advice

        advice = self.parser.parse(raw, symbol, regime)
        if not advice:
            logger.warning("Failed to parse LLM response")
            with self._advice_lock:
                return self._last_advice

        # Cache and store
        self.cache.set(symbol, prompt, advice)
        with self._advice_lock:
            self._last_advice = advice

        logger.info(
            f"[LLM ADVICE] {symbol} | Bias={advice.bias.value} | "
            f"Confidence={advice.confidence:.2f} | Score={advice.sentiment_score:+.2f} | "
            f"Risk={advice.risk_level.value} | Veto={advice.veto} | "
            f"Factors={advice.key_factors}"
        )
        return advice

    def get_advice_async(
        self,
        symbol: str,
        df_1h: pd.DataFrame,
        df_4h: pd.DataFrame,
        regime: str,
        mark_price: float,
        open_positions: List[dict],
        callback=None,
    ) -> threading.Thread:
        """
        Non-blocking version. Spawns a thread, calls LLM, then invokes callback(advice).
        Returns immediately so the trading loop is never blocked.
        """
        def _worker():
            advice = self.get_advice(symbol, df_1h, df_4h, regime, mark_price, open_positions)
            if callback:
                callback(advice)

        t = threading.Thread(target=_worker, daemon=True)
        t.start()
        return t

    def should_allow_trade(
        self,
        advice: Optional[LLMAdvice],
        technical_side: str,  # "LONG" or "SHORT"
    ) -> Tuple[bool, str]:
        """
        Decide if a technical signal should be acted upon.
        Returns (allow, reason).
        """
        if advice is None:
            return True, "No LLM advice available; proceeding on technical signal only"

        if advice.veto:
            # veto_reason is now a proper dataclass field — no hasattr needed
            reason = advice.veto_reason or "Risk too high"
            return False, f"LLM VETO: {reason}"

        if advice.confidence < self.min_confidence:
            return True, f"LLM confidence low ({advice.confidence:.2f}); technical signal takes precedence"

        # Alignment check
        tech_long = technical_side == "LONG"
        llm_bullish = advice.bias in (LLMBias.BULLISH, LLMBias.NEUTRAL) and advice.sentiment_score > 0.1
        llm_bearish = advice.bias in (LLMBias.BEARISH, LLMBias.NEUTRAL) and advice.sentiment_score < -0.1

        if tech_long and llm_bearish and advice.sentiment_score < self.veto_threshold:
            return False, f"LLM strongly disagrees with LONG (score={advice.sentiment_score:+.2f})"
        if not tech_long and llm_bullish and advice.sentiment_score > abs(self.veto_threshold):
            return False, f"LLM strongly disagrees with SHORT (score={advice.sentiment_score:+.2f})"

        # Recommended bias filter
        if advice.recommended_bias == "long_only" and not tech_long:
            return False, "LLM recommends long_only; short signal blocked"
        if advice.recommended_bias == "short_only" and tech_long:
            return False, "LLM recommends short_only; long signal blocked"
        if advice.recommended_bias == "none":
            return False, "LLM recommends no trades today"

        return True, f"LLM aligned (score={advice.sentiment_score:+.2f}, conf={advice.confidence:.2f})"

    def adjust_position_size(
        self,
        advice: Optional[LLMAdvice],
        base_margin: float,
    ) -> float:
        """
        Modify position size based on LLM risk assessment.
        Returns adjusted margin to use.
        """
        if advice is None:
            return base_margin

        multiplier = 1.0
        if advice.risk_level == LLMRiskLevel.EXTREME:
            multiplier = 0.0  # Block entirely
        elif advice.risk_level == LLMRiskLevel.HIGH:
            multiplier = 0.5
        elif advice.risk_level == LLMRiskLevel.MEDIUM:
            multiplier = 0.75
        elif advice.risk_level == LLMRiskLevel.LOW:
            multiplier = 1.0

        # Confidence scaling
        multiplier *= (0.5 + 0.5 * advice.confidence)

        return base_margin * multiplier

    def get_last_advice(self) -> Optional[LLMAdvice]:
        with self._advice_lock:
            return self._last_advice


