# Disk Cache
# ---------------------------------------------------------------------------

class LLMCache:
    """Simple file-based cache to avoid redundant LLM calls."""

    def __init__(self, ttl: int = CACHE_TTL_SECONDS, cache_dir: Path = CACHE_DIR,
                 model: str = OLLAMA_MODEL):
        self.ttl = ttl
        self.dir = cache_dir
        self.model = model
        self.dir.mkdir(exist_ok=True)

    def _key(self, symbol: str, prompt: str) -> str:
        """Hash symbol + model + prompt — different models get separate cache entries."""
        h = hashlib.sha256(f"{symbol}:{self.model}:{prompt}".encode()).hexdigest()[:16]
        return h

    def get(self, symbol: str, prompt: str) -> Optional[LLMAdvice]:
        key = self._key(symbol, prompt)
        path = self.dir / f"{symbol}_{key}.json"
        if not path.exists():
            return None
        try:
            with open(path, "r") as f:
                data = json.load(f)
            if time.time() - data.get("cached_at", 0) > self.ttl:
                return None
            # Reconstruct — include veto_reason so it survives cache round-trips
            return LLMAdvice(
                timestamp=data["timestamp"],
                symbol=data["symbol"],
                bias=LLMBias(data["bias"]),
                confidence=data["confidence"],
                sentiment_score=data["sentiment_score"],
                risk_level=LLMRiskLevel(data["risk_level"]),
                key_factors=data["key_factors"],
                recommended_bias=data["recommended_bias"],
                technical_alignment=data["technical_alignment"],
                veto=data["veto"],
                veto_reason=data.get("veto_reason"),
                raw_response=data.get("raw_response", ""),
            )
        except Exception:
            return None

    def set(self, symbol: str, prompt: str, advice: LLMAdvice):
        key = self._key(symbol, prompt)
        path = self.dir / f"{symbol}_{key}.json"
        data = advice.to_dict()
        data["cached_at"] = int(time.time())
        data["raw_response"] = advice.raw_response[:500]  # Truncate
        with open(path, "w") as f:
            json.dump(data, f, indent=2)


