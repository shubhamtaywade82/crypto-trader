class LLMResponseParser:
    """Parses raw LLM text into structured LLMAdvice."""

    @staticmethod
    def parse(raw: str, symbol: str, technical_regime: str) -> Optional[LLMAdvice]:
        if not raw:
            return None

        # Strip <think>...</think> blocks emitted by Qwen3/3.5 thinking models
        # even when think:false is set, some quantised versions still emit them.
        import re
        text = re.sub(r"<think>.*?</think>", "", raw, flags=re.DOTALL).strip()
        if not text:
            logger.warning("LLM response was only a <think> block — no JSON produced")
            return None

        # Extract JSON block if wrapped in markdown
        if "```json" in text:
            text = text.split("```json")[1].split("```")[0].strip()
        elif "```" in text:
            text = text.split("```")[1].split("```")[0].strip()

        # Fallback: find outermost { ... } block
        start = text.find("{")
        end = text.rfind("}") + 1
        if start != -1 and end > start:
            text = text[start:end]

        try:
            data = json.loads(text)
        except json.JSONDecodeError:
            logger.warning(f"LLM returned invalid JSON: {raw[:200]}")
            return None

        # Validate and coerce fields
        bias_str = data.get("bias", "unclear").lower()
        bias = LLMBias(bias_str) if bias_str in [e.value for e in LLMBias] else LLMBias.UNCLEAR

        # BUG FIX: was corrupted to "   0, conf))" — restored full clamp expression
        conf = float(data.get("confidence", 0.5))
        conf = max(0.0, min(1.0, conf))

        score = float(data.get("sentiment_score", 0.0))
        score = max(-1.0, min(1.0, score))

        risk_str = data.get("risk_level", "medium").lower()
        risk = LLMRiskLevel(risk_str) if risk_str in [e.value for e in LLMRiskLevel] else LLMRiskLevel.MEDIUM

        factors = data.get("key_factors", [])
        if not isinstance(factors, list):
            factors = [str(factors)]

        rec = data.get("recommended_bias", "any")
        if rec not in ("long_only", "short_only", "any", "none"):
            rec = "any"

        align = float(data.get("technical_alignment", 0.0))
        align = max(-1.0, min(1.0, align))

        veto_reason = data.get("veto_reason")
        veto_reason_str = str(veto_reason).strip() if veto_reason else None
        veto = bool(veto_reason_str)  # True only when veto_reason is a non-empty string

        return LLMAdvice(
            timestamp=int(time.time()),
            symbol=symbol,
            bias=bias,
            confidence=conf,
            sentiment_score=score,
            risk_level=risk,
            key_factors=factors[:5],  # Cap at 5
            recommended_bias=rec,
            technical_alignment=align,
            veto=veto,
            veto_reason=veto_reason_str,
            raw_response=raw,
        )


