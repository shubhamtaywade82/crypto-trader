class OllamaClient:
    """Lightweight async-capable client for Ollama API."""

    def __init__(
        self,
        host: str = OLLAMA_HOST,
        model: str = OLLAMA_MODEL,
        timeout: int = OLLAMA_TIMEOUT,
        max_tokens: int = OLLAMA_MAX_TOKENS,
    ):
        self.host = host.rstrip("/")
        self.model = model
        self.timeout = timeout
        self.max_tokens = max_tokens
        self.session = requests.Session()

    def is_available(self) -> bool:
        """Check if Ollama server is running."""
        try:
            resp = self.session.get(f"{self.host}/api/tags", timeout=5)
            return resp.status_code == 200
        except Exception:
            return False

    def generate(
        self,
        prompt: str,
        system: str = SYSTEM_PROMPT,
        temperature: float = 0.3,  # Low temp for consistent JSON
    ) -> Optional[str]:
        """Send prompt to Ollama and return raw text."""
        payload = {
            "model": self.model,
            "prompt": prompt,
            "system": system,
            "stream": False,
            "think": False,   # Disable chain-of-thought on Qwen3/3.5 thinking models;
                              # has no effect on non-thinking models (llama3.2, etc.)
            "options": {
                "temperature": temperature,
                "num_predict": self.max_tokens,
            },
        }
        try:
            resp = self.session.post(
                f"{self.host}/api/generate",
                json=payload,
                timeout=self.timeout,
            )
            resp.raise_for_status()
            data = resp.json()
            response_text = data.get("response", "").strip()
            if not response_text and "thinking" in data:
                response_text = data["thinking"].strip()
            return response_text
        except requests.Timeout:
            logger.warning("Ollama request timed out")
            return None
        except Exception as e:
            logger.warning(f"Ollama request failed: {e}")
            return None


