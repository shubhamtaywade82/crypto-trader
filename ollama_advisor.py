SYSTEM_PROMPT = """You are a quantitative crypto futures trading advisor.
You analyze market data and return ONLY a JSON object. No markdown, no explanation outside the JSON.

Rules:
1. You are advisory only. You do NOT place orders.
2. Base your analysis on price action, volume, momentum, and market structure.
3. Be conservative — it is better to say "neutral" than to force a wrong bias.
4. If the setup looks like a trap (e.g., breakout on declining volume), flag HIGH risk.
5. If price is near a major liquidation cluster or funding is extreme, mention it.

Output JSON schema:
{
  "bias": "bullish" | "bearish" | "neutral" | "unclear",
  "confidence": 0.0 to 1.0,
  "sentiment_score": -1.0 to 1.0,
  "risk_level": "low" | "medium" | "high" | "extreme",
  "key_factors": ["factor 1", "factor 2", ...],
  "recommended_bias": "long_only" | "short_only" | "any" | "none",
  "technical_alignment": -1.0 to 1.0,
  "veto_reason": null | "string explaining why no trade should be taken"
}"""


def build_market_prompt(
    symbol: str,
    df_1h: pd.DataFrame,
    df_4h: pd.DataFrame,
    regime: str,
    mark_price: float,
    open_positions: List[dict],
) -> str:
    """Build a rich, structured prompt from current market data."""

    # Summarize 1H data
    recent_1h = df_1h.tail(6)
    h1_summary = []
    for _, row in recent_1h.iterrows():
        direction = "▲" if row["close"] > row["open"] else "▼"
        h1_summary.append(
            f"{direction} O:{row['open']:.2f} H:{row['high']:.2f} L:{row['low']:.2f} C:{row['close']:.2f} V:{row['volume']:.0f}"
        )

    # Summarize 4H data
    recent_4h = df_4h.tail(4)
    h4_summary = []
    for _, row in recent_4h.iterrows():
        direction = "▲" if row["close"] > row["open"] else "▼"
        h4_summary.append(
            f"{direction} O:{row['open']:.2f} H:{row['high']:.2f} L:{row['low']:.2f} C:{row['close']:.2f} V:{row['volume']:.0f}"
        )

    # Compute quick stats
    change_24h = (
        (mark_price - df_1h["close"].iloc[-24]) / df_1h["close"].iloc[-24] * 100
        if len(df_1h) >= 24 else 0
    )
    volume_24h = df_1h["volume"].tail(24).sum()
    avg_volume_20 = df_1h["volume"].tail(20).mean()
    volume_surge = (df_1h["volume"].iloc[-1] / avg_volume_20 - 1) * 100 if avg_volume_20 > 0 else 0

    # Open position context — use .get() with defaults to avoid KeyError / ZeroDivisionError
    pos_context = "No open positions."
    if open_positions:
        p = open_positions[0]
        margin = p.get("margin_used") or 1.0   # avoid ZeroDivisionError
        upnl = p.get("unrealized_pnl", 0.0)
        pct = upnl / margin * 100
        pos_context = (
            f"Open {p.get('side', '?')} from {p.get('entry_price', 0):.2f}, "
            f"current unrealized PnL: {upnl:.2f} USDT ({pct:.1f}% on margin)"
        )

    prompt = f"""Analyze the following market data for {symbol} and return ONLY JSON.

Current Price: {mark_price:.2f}
24H Change: {change_24h:+.2f}%
24H Volume: {volume_24h:,.0f}
Last 1H Volume vs 20-candle avg: {volume_surge:+.1f}%
Technical Regime: {regime}

Last 6 x 1H candles (newest last):
{chr(10).join(h1_summary)}

Last 4 x 4H candles (newest last):
{chr(10).join(h4_summary)}

Position Context: {pos_context}

Question: Based on this data, what is your bias, confidence, and risk assessment?
Return ONLY the JSON object."""

    return prompt


