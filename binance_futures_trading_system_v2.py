class RiskManager:
    """Enforces daily trade limits and consecutive loss stops."""

    def __init__(self, max_daily: int = MAX_DAILY_TRADES, max_consec: int = MAX_CONSEC_LOSS):
        self.max_daily = max_daily
        self.max_consec = max_consec
        self.daily_count = 0
        self.last_trade_date: Optional[date] = None
        self.consecutive_losses = 0
        self.state_file = DATA_DIR / "risk_manager_state.json"
        self._load_state()

    def _today(self) -> date:
        return datetime.now(timezone.utc).date()

    def can_trade(self) -> Tuple[bool, str]:
        today = self._today()
        if self.last_trade_date != today:
            self.daily_count = 0
            self.last_trade_date = today

        if self.daily_count >= self.max_daily:
            return False, f"Daily trade limit reached ({self.max_daily})"
        if self.consecutive_losses >= self.max_consec:
            return False, f"Consecutive loss limit reached ({self.max_consec}) — trading halted"
        return True, "OK"

    def record_open(self):
        today = self._today()
        if self.last_trade_date != today:
            self.daily_count = 0
            self.last_trade_date = today
        self.daily_count += 1
        self._save_state()

    def record_close(self, realized_pnl: float):
        if realized_pnl > 0:
            self.consecutive_losses = 0
        else:
            self.consecutive_losses += 1
        self._save_state()

    def _save_state(self):
        state = {
            "daily_count": self.daily_count,
            "last_trade_date": self.last_trade_date.isoformat() if self.last_trade_date else None,
            "consecutive_losses": self.consecutive_losses,
        }
        with open(self.state_file, "w") as f:
            json.dump(state, f)

    def _load_state(self):
        if not self.state_file.exists():
            return
        try:
            with open(self.state_file, "r") as f:
                state = json.load(f)
            self.daily_count = state.get("daily_count", 0)
            d = state.get("last_trade_date")
            self.last_trade_date = date.fromisoformat(d) if d else None
            self.consecutive_losses = state.get("consecutive_losses", 0)
        except Exception as e:
            logger.warning(f"RiskManager load failed: {e}")

    def reset(self):
        self.daily_count = 0
        self.consecutive_losses = 0
        self.last_trade_date = None
        if self.state_file.exists():
            self.state_file.unlink()


