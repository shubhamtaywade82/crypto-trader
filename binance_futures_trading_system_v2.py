class MarketRegimeAnalyzer:
    """Determines trend bias from 4H structure."""

    def analyze(self, df: pd.DataFrame) -> Tuple[MarketRegime, pd.DataFrame]:
        if len(df) < 30:
            return MarketRegime.CHOP, df

        df = df.copy()
        df["ema9"] = compute_ema(df, 9)
        df["ema21"] = compute_ema(df, 21)
        df["rsi"] = compute_rsi(df["close"], 14)

        latest = df.iloc[-1]
        price = latest["close"]
        ema9, ema21 = latest["ema9"], latest["ema21"]

        # EMA distance as % of price
        ema_dist = abs(ema9 - ema21) / price

        # Pivot structure
        ph, pl = find_pivots(df, window=2)

        # Check HH/HL or LH/LL using last 3 pivots
        hh_hl = False
        lh_ll = False
        if len(ph) >= 3 and len(pl) >= 3:
            last_ph = [p[1] for p in ph[-3:]]
            last_pl = [p[1] for p in pl[-3:]]
            if last_ph[0] < last_ph[1] < last_ph[2] and last_pl[0] < last_pl[1] < last_pl[2]:
                hh_hl = True
            if last_ph[0] > last_ph[1] > last_ph[2] and last_pl[0] > last_pl[1] > last_pl[2]:
                lh_ll = True

        # Regime classification
        if ema9 > ema21 and price > ema21 and hh_hl:
            regime = MarketRegime.TRENDING_UP
        elif ema9 < ema21 and price < ema21 and lh_ll:
            regime = MarketRegime.TRENDING_DOWN
        elif ema_dist < 0.005:
            regime = MarketRegime.CHOP
        else:
            # Check if ranging (oscillating between levels)
            recent = df.iloc[-20:]
            range_pct = (recent["high"].max() - recent["low"].min()) / price
            if range_pct < 0.08 and not hh_hl and not lh_ll:
                regime = MarketRegime.RANGING
            else:
                # Default to weak trend direction if EMAs aligned but no structure
                if ema9 > ema21:
                    regime = MarketRegime.TRENDING_UP
                elif ema9 < ema21:
                    regime = MarketRegime.TRENDING_DOWN
                else:
                    regime = MarketRegime.CHOP

        return regime, df


