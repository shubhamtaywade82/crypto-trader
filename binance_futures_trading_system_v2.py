class PlaybookA_IntradaySnap:
    """
    6–16 hour hold.
    Entry: 1H pullback to EMA21 within 4H trend + volume + RSI + rejection candle.
    """

    def evaluate(
        self,
        df_1h: pd.DataFrame,
        regime: MarketRegime,
    ) -> Optional[Dict]:
        if len(df_1h) < 30:
            return None

        # Only trade in direction of 4H trend
        if regime == MarketRegime.TRENDING_UP:
            direction = PositionSide.LONG
        elif regime == MarketRegime.TRENDING_DOWN:
            direction = PositionSide.SHORT
        elif regime == MarketRegime.RANGING:
            # In ranging markets, trade both sides at extremes (simplified: skip for now)
            return None
        else:
            return None

        df = df_1h.copy()
        df["ema21"] = compute_ema(df, A_EMA)
        df["rsi"] = compute_rsi(df["close"], 14)
        df["vol_avg20"] = df["volume"].rolling(20).mean()

        # Current and previous candle
        curr = df.iloc[-1]
        prev = df.iloc[-2]
        price = curr["close"]

        # Volume check
        if curr["volume"] < curr["vol_avg20"] * A_VOL_MULT:
            return None

        # RSI check
        rsi = curr["rsi"]
        if pd.isna(rsi) or not (A_RSI_LO <= rsi <= A_RSI_HI):
            return None

        # Pullback + Rejection logic
        ema21 = curr["ema21"]
        if pd.isna(ema21):
            return None

        if direction == PositionSide.LONG:
            # Pullback: price touched or went below EMA21, or within 0.3%
            pullback = (curr["low"] <= ema21 * 1.003) or (abs(price - ema21) / price < 0.003)
            if not pullback:
                return None
            # Rejection: lower wick >= 1.5x body OR bullish engulfing
            body = abs(curr["close"] - curr["open"])
            lower_wick = min(curr["open"], curr["close"]) - curr["low"]
            bullish_engulfing = (curr["close"] > prev["open"]) and (curr["open"] < prev["close"]) and (curr["close"] > curr["open"])
            if not (lower_wick >= body * 1.5 or bullish_engulfing):
                return None
            sl = price * (1 - A_SL_PCT)
            tp = price * (1 + A_TP_PCT)

        else:  # SHORT
            pullback = (curr["high"] >= ema21 * 0.997) or (abs(price - ema21) / price < 0.003)
            if not pullback:
                return None
            body = abs(curr["close"] - curr["open"])
            upper_wick = curr["high"] - max(curr["open"], curr["close"])
            bearish_engulfing = (curr["close"] < prev["open"]) and (curr["open"] > prev["close"]) and (curr["close"] < curr["open"])
            if not (upper_wick >= body * 1.5 or bearish_engulfing):
                return None
            sl = price * (1 + A_SL_PCT)
            tp = price * (1 - A_TP_PCT)

        return {
            "playbook": Playbook.INTRADAY,
            "side": direction,
            "entry_price": price,
            "sl_price": sl,
            "tp_price": tp,
            "time_stop_hours": A_TIME_H,
            "reason": f"PlaybookA: 1H pullback to EMA21 + vol + RSI({rsi:.1f})",
        }


