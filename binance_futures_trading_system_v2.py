class PlaybookB_Swing:
    """
    24–48 hour hold.
    Entry: 4H breakout with volume, 1H retest of broken level.
    Scaled exits: 50% at +1%, 25% at +2%, runner trails 1H EMA9.
    """

    def evaluate(
        self,
        df_1h: pd.DataFrame,
        df_4h: pd.DataFrame,
        regime: MarketRegime,
    ) -> Optional[Dict]:
        if len(df_4h) < 20 or len(df_1h) < 30:
            return None

        # Only trade in clear trend direction
        if regime == MarketRegime.TRENDING_UP:
            direction = PositionSide.LONG
        elif regime == MarketRegime.TRENDING_DOWN:
            direction = PositionSide.SHORT
        else:
            return None

        # 4H analysis
        df4 = df_4h.copy()
        df4["ema9"] = compute_ema(df4, 9)
        df4["ema21"] = compute_ema(df4, 21)
        df4["rsi"] = compute_rsi(df4["close"], 14)
        df4["vol_avg20"] = df4["volume"].rolling(20).mean()

        # Check last 4H candle for breakout
        c4 = df4.iloc[-1]
        p4 = df4.iloc[-2] if len(df4) > 1 else c4
        body_pct = abs(c4["close"] - c4["open"]) / c4["open"]

        if body_pct < B_BODY_MIN:
            return None
        if c4["volume"] < c4["vol_avg20"] * B_VOL_MULT:
            return None

        rsi_4h = c4["rsi"]
        if pd.isna(rsi_4h):
            return None

        # Breakout level = previous resistance/support (last 6 candles high/low)
        if direction == PositionSide.LONG:
            if not (c4["close"] > c4["open"] and c4["close"] > p4["high"]):
                return None
            if not (B_RSI_LONG_LO <= rsi_4h <= B_RSI_LONG_HI):
                return None
            breakout_level = df4.iloc[-7:-1]["high"].max()  # resistance before breakout
        else:
            if not (c4["close"] < c4["open"] and c4["close"] < p4["low"]):
                return None
            if not (B_RSI_SHORT_LO <= rsi_4h <= B_RSI_SHORT_HI):
                return None
            breakout_level = df4.iloc[-7:-1]["low"].min()

        # 1H retest check: current price is within 0.5% of breakout level
        # AND 1H candle closes back in breakout direction
        df1 = df_1h.copy()
        c1 = df1.iloc[-1]
        price = c1["close"]

        if direction == PositionSide.LONG:
            near_level = abs(price - breakout_level) / price < 0.005 or c1["low"] <= breakout_level * 1.005
            if not (near_level and c1["close"] > c1["open"]):
                return None
            sl = price * (1 - B_SL_PCT)
            tp1 = price * (1 + B_TP1_PCT)
            tp2 = price * (1 + B_TP2_PCT)
        else:
            near_level = abs(price - breakout_level) / price < 0.005 or c1["high"] >= breakout_level * 0.995
            if not (near_level and c1["close"] < c1["open"]):
                return None
            sl = price * (1 + B_SL_PCT)
            tp1 = price * (1 - B_TP1_PCT)
            tp2 = price * (1 - B_TP2_PCT)

        return {
            "playbook": Playbook.SWING,
            "side": direction,
            "entry_price": price,
            "sl_price": sl,
            "tp_levels": [
                {"price": tp1, "pct": 0.50, "hit": False, "label": "TP1"},
                {"price": tp2, "pct": 0.25, "hit": False, "label": "TP2"},
            ],
            "time_stop_hours": B_TIME_H,
            "reason": f"PlaybookB: 4H breakout + 1H retest | RSI(4H)={rsi_4h:.1f}",
        }


